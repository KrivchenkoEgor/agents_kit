# -*- coding: utf-8 -*-
"""
15_compare_august_forecast_fact.py — Сверка прогноза августа-2026 с фактом
==========================================================================
Пользователь прислал новый файл data/МОлокоМ08 (1).xlsx с продажами 1–9 августа.
Сверяем подневный прогноз (скрипт 14) с фактом по каждому дню и каждому товару.

Правила:
  - факт 1–3 августа уже был в исходных данных и входил в прогноз как факт —
    сверяем их отдельно (контроль, что файлы из одного источника);
  - содержательная сверка — по дням 4–9 августа (первые 6 прогнозных дней);
  - коды нового файла склеиваются в «истории» как в скрипте 14 (шринкфляция);
  - если товар продавался, но прогноза не было — строка «продажи без прогноза»;
  - если прогноз был, а продаж нет — отклонение −100%.

Выход: output/Отчет_расхождения_прогноз_факт.xlsx
"""

import numpy as np
import pandas as pd

# ---------------------------------------------------------------
# 1. Прогноз из скрипта 14 (факт 1–3 + прогноз 4–31)
# ---------------------------------------------------------------
fc = pd.read_excel(
    "output/Прогноз_август_2026.xlsx",
    sheet_name="Август_по_дням",
    dtype={"Код истории": str},
)
# Excel превратил «00014» в число 14 — нормализуем до 6 знаков с обеих сторон
fc["Код истории"] = fc["Код истории"].str.zfill(6)
fc = fc[["Дата", "Код истории", "Название товара (история)", "Прогноз, штук", "Прогноз выручки, руб"]].copy()
fc["Дата"] = pd.to_datetime(fc["Дата"]).dt.date

# ---------------------------------------------------------------
# 2. Факт из нового файла → истории (как в скрипте 14)
# ---------------------------------------------------------------
df = pd.read_excel(
    "data/МОлокоМ08 (1).xlsx",
    dtype={"Код номенклатуры": str},
    parse_dates=["День"],
)
pairs = pd.read_excel("output/пары_шринкфляции.xlsx", dtype=str)

chain_map = {}
for _, p in pairs.iterrows():
    chain_map[p["Код старой упаковки"]] = p["Код старой упаковки"]
    chain_map[p["Код новой упаковки"]] = p["Код старой упаковки"]
for code in df["Код номенклатуры"].unique():
    chain_map.setdefault(code, code)

df["История"] = df["Код номенклатуры"].map(chain_map).str.zfill(6)
first_name = df.groupby("История")["Номенклатура"].first().to_dict()

fact = (
    df.groupby(["День", "История"])
    .agg(Факт_штук=("ТО, в е.изм.", "sum"), Факт_руб=("ТО, руб", "sum"))
    .reset_index()
)
fact["Дата"] = fact["День"].dt.date
fact = fact.drop(columns=["День"]).rename(columns={"История": "Код истории"})

# ---------------------------------------------------------------
# 3. Контроль факта 1–3: совпадает ли с тем, что было в прогнозе
# ---------------------------------------------------------------
fc_fact = fc[fc["Дата"] <= pd.Timestamp("2026-08-03").date()]
fact_13 = fact[fact["Дата"] <= pd.Timestamp("2026-08-03").date()]
ok_13 = (
    abs(fc_fact.groupby("Дата")["Прогноз, штук"].sum() - fact_13.groupby("Дата")["Факт_штук"].sum()).max() < 0.5
)
print("Контроль: факт 1–3 августа в новом файле совпадает с исходным:", "да" if ok_13 else "НЕТ!")

# ---------------------------------------------------------------
# 4. Сверка по дням 4–9 августа
# ---------------------------------------------------------------
D0, D1 = pd.Timestamp("2026-08-04").date(), pd.Timestamp("2026-08-09").date()
fc46 = fc[(fc["Дата"] >= D0) & (fc["Дата"] <= D1)]
fact46 = fact[(fact["Дата"] >= D0) & (fact["Дата"] <= D1)]

m = fc46.merge(fact46, on=["Дата", "Код истории"], how="outer", indicator=True)
m["Факт_штук"] = m["Факт_штук"].fillna(0.0)
m["Факт_руб"] = m["Факт_руб"].fillna(0.0)
m["Прогноз, штук"] = m["Прогноз, штук"].fillna(0.0)
m["Прогноз выручки, руб"] = m["Прогноз выручки, руб"].fillna(0.0)

# Названия: из прогноза, для «новых» — из факта
m["Название товара (история)"] = m["Название товара (история)"].fillna(
    m["Код истории"].map(first_name)
)

m["Отклонение, штук"] = (m["Факт_штук"] - m["Прогноз, штук"]).round(1)
m["Отклонение, руб"] = (m["Факт_руб"] - m["Прогноз выручки, руб"]).round(2)
with np.errstate(divide="ignore", invalid="ignore"):
    m["Отклонение, %"] = np.where(
        m["Прогноз, штук"] > 0, (m["Факт_штук"] / m["Прогноз, штук"] - 1) * 100, np.nan
    )
m["Отклонение, %"] = m["Отклонение, %"].round(1)

def comment(r):
    if r["_merge"] == "right_only":
        return "продажи без прогноза (товар не был в базе прогноза)"
    if r["Прогноз, штук"] > 0 and r["Факт_штук"] == 0:
        return "прогноз был, продаж нет"
    if r["Прогноз, штук"] == 0 and r["Факт_штук"] > 0:
        return "прогноз 0 (товар не продавался в мае–июле), но продажи есть"
    if r["Прогноз, штук"] == 0 and r["Факт_штук"] == 0:
        return ""
    return ""

m["Комментарий"] = m.apply(comment, axis=1)

m = m.rename(columns={"Факт_штук": "Факт, штук", "Факт_руб": "Факт, руб"})

cols = [
    "Дата", "Код истории", "Название товара (история)",
    "Прогноз, штук", "Факт, штук", "Отклонение, штук", "Отклонение, %",
    "Прогноз выручки, руб", "Факт, руб", "Отклонение, руб", "Комментарий",
]
m = m[cols].sort_values(["Дата", "Код истории"]).reset_index(drop=True)

# ---------------------------------------------------------------
# 5. Итоги по товарам (4–9 августа)
# ---------------------------------------------------------------
by_prod = (
    m.groupby(["Код истории", "Название товара (история)"])
    .agg(
        Прогноз_штук=("Прогноз, штук", "sum"),
        Факт_штук=("Факт, штук", "sum"),
        Прогноз_руб=("Прогноз выручки, руб", "sum"),
        Факт_руб=("Факт, руб", "sum"),
    )
    .reset_index()
)
with np.errstate(divide="ignore", invalid="ignore"):
    by_prod["Отклонение, %"] = np.where(
        by_prod["Прогноз_штук"] > 0,
        (by_prod["Факт_штук"] / by_prod["Прогноз_штук"] - 1) * 100,
        np.nan,
    )
by_prod["Отклонение, штук"] = (by_prod["Факт_штук"] - by_prod["Прогноз_штук"]).round(1)
by_prod["Отклонение, руб"] = (by_prod["Факт_руб"] - by_prod["Прогноз_руб"]).round(2)
by_prod = by_prod.sort_values("Отклонение, штук", key=lambda s: s.abs(), ascending=False).reset_index(drop=True)
by_prod["Отклонение, %"] = by_prod["Отклонение, %"].round(1)
by_prod = by_prod.rename(
    columns={
        "Прогноз_штук": "Прогноз, штук", "Факт_штук": "Факт, штук",
        "Прогноз_руб": "Прогноз, руб", "Факт_руб": "Факт, руб",
    }
)

# ---------------------------------------------------------------
# 6. Итоги по дням (4–9 августа)
# ---------------------------------------------------------------
by_day = (
    m.groupby("Дата")
    .agg(
        Прогноз_штук=("Прогноз, штук", "sum"),
        Факт_штук=("Факт, штук", "sum"),
        Прогноз_руб=("Прогноз выручки, руб", "sum"),
        Факт_руб=("Факт, руб", "sum"),
    )
    .reset_index()
)
with np.errstate(divide="ignore", invalid="ignore"):
    by_day["Отклонение, %"] = (
        (by_day["Факт_штук"] / by_day["Прогноз_штук"] - 1) * 100
    ).round(1)
by_day["Отклонение, штук"] = (by_day["Факт_штук"] - by_day["Прогноз_штук"]).round(1)
by_day["Отклонение, руб"] = (by_day["Факт_руб"] - by_day["Прогноз_руб"]).round(2)
by_day = by_day.rename(
    columns={
        "Прогноз_штук": "Прогноз, штук", "Факт_штук": "Факт, штук",
        "Прогноз_руб": "Прогноз, руб", "Факт_руб": "Факт, руб",
    }
)

# ---------------------------------------------------------------
# 7. Сводка
# ---------------------------------------------------------------
tot_p, tot_f = m["Прогноз, штук"].sum(), m["Факт, штук"].sum()
tot_pr, tot_fr = m["Прогноз выручки, руб"].sum(), m["Факт, руб"].sum()
n_combos = len(m)
n_sold = int((m["Факт, штук"] > 0).sum())

w = m[m["Прогноз, штук"] > 0].copy()
w["В_пределах_20"] = (w["Факт, штук"] >= 0.8 * w["Прогноз, штук"]) & (w["Факт, штук"] <= 1.2 * w["Прогноз, штук"])
w["В_пределах_50"] = (w["Факт, штук"] >= 0.5 * w["Прогноз, штук"]) & (w["Факт, штук"] <= 1.5 * w["Прогноз, штук"])

summary = pd.DataFrame(
    {
        "Показатель": [
            "Факт 1–3 авг в новом файле совпадает с исходным",
            "Период сверки",
            "Прогноз на 4–9 авг, штук",
            "Факт 4–9 авг, штук",
            "Отклонение, штук",
            "Отклонение, %",
            "Прогноз на 4–9 авг, руб",
            "Факт 4–9 авг, руб",
            "Отклонение, руб",
            "Пар «день × товар» в сверке",
            "Из них с продажами",
            "Товаров без прогноза (продажи есть, прогноза не было)",
            "Дней/товаров в пределах ±20%",
            "Дней/товаров в пределах ±50%",
        ],
        "Значение": [
            "да" if ok_13 else "НЕТ",
            f"{D0} … {D1}",
            round(tot_p, 1),
            round(tot_f, 1),
            round(tot_f - tot_p, 1),
            round((tot_f / tot_p - 1) * 100, 1) if tot_p else None,
            round(tot_pr, 2),
            round(tot_fr, 2),
            round(tot_fr - tot_pr, 2),
            n_combos,
            n_sold,
            int((m["Комментарий"].str.startswith("продажи без прогноза")).sum()),
            f"{int(w['В_пределах_20'].sum())} из {len(w)} ({w['В_пределах_20'].mean()*100:.0f}%)",
            f"{int(w['В_пределах_50'].sum())} из {len(w)} ({w['В_пределах_50'].mean()*100:.0f}%)",
        ],
    }
)

# ---------------------------------------------------------------
# 8. Печать и сохранение
# ---------------------------------------------------------------
print("\n" + "=" * 78)
print(f"СВЕРКА ПРОГНОЗА И ФАКТА, {D0} … {D1}")
print("=" * 78)
print(summary.to_string(index=False))
print(f"\nПо товарам (топ-10 по отклонению в штуках):")
print(by_prod.head(10).to_string(index=False))
print(f"\nПо дням:")
print(by_day.to_string(index=False))

OUT = "output/Отчет_расхождения_прогноз_факт.xlsx"
with pd.ExcelWriter(OUT, engine="openpyxl") as writer:
    summary.to_excel(writer, sheet_name="Сводка", index=False)
    m.to_excel(writer, sheet_name="Сверка_по_дням_и_товарам", index=False)
    by_prod.to_excel(writer, sheet_name="Итоги_по_товарам", index=False)
    by_day.to_excel(writer, sheet_name="Итоги_по_дням", index=False)
    # Справочно: весь факт 1–9 из нового файла
    fact_full = df.groupby(["День", "История"]).agg(
        Факт_штук=("ТО, в е.изм.", "sum"), Факт_руб=("ТО, руб", "sum")
    ).reset_index()
    fact_full["Название товара (история)"] = fact_full["История"].map(first_name)
    fact_full["Дата"] = fact_full["День"].dt.date
    fact_full = fact_full[["Дата", "История", "Название товара (история)", "Факт_штук", "Факт_руб"]].sort_values(["Дата", "История"])
    fact_full.to_excel(writer, sheet_name="Факт_1_9_весь", index=False)

print(f"\nСохранено: {OUT}")
print("  Лист «Сводка»: итоговые цифры")
print("  Лист «Сверка_по_дням_и_товарам»:", len(m), "строк (день × товар)")
print("  Лист «Итоги_по_товарам»:", len(by_prod), "товаров")
print("  Лист «Итоги_по_дням»:", len(by_day), "дней")
print("  Лист «Факт_1_9_весь»:", len(fact_full), "строк (весь факт из нового файла)")
