# -*- coding: utf-8 -*-
"""
19_top5_sausage.py — Топ-5 самых продаваемых позиций в каждой группе
===================================================================
Задача пользователя: показать 5 самых продаваемых позиций в каждой
группе товаров за ВСЁ время (2023-01-01 … 2026-08-10) — по количеству
и по выручке; создать Excel-отчёт.

Единицы количества — с учётом поправки пользователя (см. 18):
  весовые товары (есть хоть одна дробная продажа) — кг;
  штучные товары (все продажи целые) — количество упаковок, шт.
Колонка «Продано ≈ кг» переводит штучные в килограммы (шт × фасовка
из названия) для честного сравнения с весовыми.

Выход: output/Отчет_топ5_колбаса_по_группам.xlsx
  Лист 1: Топ-5_по_количеству — по каждой группе 5 лидеров по шт/кг
  Лист 2: Топ-5_по_выручке    — по каждой группе 5 лидеров по руб
  Лист 3: Сводка_по_группам   — итоги по группе + лидеры
  Лист 4: Методика
"""

import re
import numpy as np
import pandas as pd

# ---------------------------------------------------------------
# Чтение
# ---------------------------------------------------------------
df = pd.read_excel(
    "data/колбасаНФ.xlsx",
    dtype={"Код ": str},
    parse_dates=["День"],
)
df = df.rename(columns={"Код ": "Код"})

# только «настоящие» продажи
s = df[(df["ТО, в е.изм."] > 0) & (df["ТО, руб"] > 0)].copy()
print(f"Весь период: {s['День'].min().date()} … {s['День'].max().date()} "
      f"({len(s):,} строк продаж)".replace(",", " "))

# ---------------------------------------------------------------
# Фасовка из названия (350г → 350; «1кг» → 1000)
# ---------------------------------------------------------------
def parse_weight(name):
    m = re.search(r"(\d+(?:[.,]\d+)?)\s*(г|кг)\b", str(name))
    if not m:
        return None
    v = float(m.group(1).replace(",", "."))
    return v * 1000 if m.group(2) == "кг" else v

# ---------------------------------------------------------------
# Сводка по коду за всё время
# ---------------------------------------------------------------
agg = (
    s.groupby(["группа", "Код"])
    .agg(
        Название=("Номенклатура", "first"),
        Выручка_руб=("ТО, руб", "sum"),
        Продано_ед=("ТО, в е.изм.", "sum"),
        Дней_продаж=("День", "nunique"),
        Первая_продажа=("День", "min"),
        Последняя_продажа=("День", "max"),
    )
    .reset_index()
)
print(f"Товаров за всё время: {len(agg)} | групп: {agg['группа'].nunique()}")

# Тип продажи (правило пользователя): есть дробная продажа → весовой, кг
prod_type = s.groupby("Код")["ТО, в е.изм."].apply(
    lambda v: "весовой, кг" if ((v - np.floor(v)) > 1e-9).any() else "штучный, шт"
)
agg["Тип"] = agg["Код"].map(prod_type)

# «≈ кг»: весовые — их же кг; штучные — шт × фасовка из названия
agg["Фасовка_г"] = agg["Название"].map(parse_weight)
agg["Эквивалент_кг"] = agg["Продано_ед"].astype(float)
sh_kg = agg["Тип"] == "штучный, шт"
agg.loc[sh_kg, "Эквивалент_кг"] = agg.loc[sh_kg, "Продано_ед"] * agg.loc[sh_kg, "Фасовка_г"] / 1000
agg["Эквивалент_кг"] = agg["Эквивалент_кг"].round(1)
agg["Выручка_руб"] = agg["Выручка_руб"].round(2)
agg["Продано_ед"] = agg["Продано_ед"].round(1)

# ---------------------------------------------------------------
# Топ-5 в каждой группе: по количеству (шт/кг) и по выручке
# ---------------------------------------------------------------
TOP_N = 5

def top5(tbl, sort_col):
    """5 лидеров группы по показателю (при равенстве — первым меньший код)."""
    t = tbl.sort_values(["группа", sort_col, "Код"], ascending=[True, False, True])
    t["Место"] = t.groupby("группа").cumcount() + 1
    return t[t["Место"] <= TOP_N]

top_qty = top5(agg, "Продано_ед")
top_rev = top5(agg, "Выручка_руб")

# ---------------------------------------------------------------
# Лист 1: топ-5 по количеству
# ---------------------------------------------------------------
sh_qty = top_qty.rename(columns={
    "группа": "Группа",
    "Название": "Название товара",
    "Тип": "Тип продажи",
    "Продано_ед": "Продано за всё время, шт/кг",
    "Эквивалент_кг": "Продано ≈ кг",
    "Выручка_руб": "Выручка за всё время, руб",
    "Дней_продаж": "Дней с продажами",
    "Первая_продажа": "Первая продажа",
    "Последняя_продажа": "Последняя продажа",
    "Место": "Место в группе",
})
sh_qty["Первая продажа"] = sh_qty["Первая продажа"].dt.date
sh_qty["Последняя продажа"] = sh_qty["Последняя продажа"].dt.date
sh_qty["Продано ≈ кг"] = sh_qty["Продано ≈ кг"].replace({"": "—"}).fillna("—")
sh_qty = sh_qty[["Группа", "Место в группе", "Код", "Название товара", "Тип продажи",
                 "Продано за всё время, шт/кг", "Продано ≈ кг", "Выручка за всё время, руб",
                 "Дней с продажами", "Первая продажа", "Последняя продажа"]]

# ---------------------------------------------------------------
# Лист 2: топ-5 по выручке
# ---------------------------------------------------------------
sh_rev = top_rev.rename(columns={
    "группа": "Группа",
    "Название": "Название товара",
    "Тип": "Тип продажи",
    "Продано_ед": "Продано за всё время, шт/кг",
    "Эквивалент_кг": "Продано ≈ кг",
    "Выручка_руб": "Выручка за всё время, руб",
    "Дней_продаж": "Дней с продажами",
    "Первая_продажа": "Первая продажа",
    "Последняя_продажа": "Последняя продажа",
    "Место": "Место в группе",
})
sh_rev["Первая продажа"] = sh_rev["Первая продажа"].dt.date
sh_rev["Последняя продажа"] = sh_rev["Последняя продажа"].dt.date
sh_rev["Продано ≈ кг"] = sh_rev["Продано ≈ кг"].replace({"": "—"}).fillna("—")
sh_rev = sh_rev[["Группа", "Место в группе", "Код", "Название товара", "Тип продажи",
                 "Выручка за всё время, руб", "Продано за всё время, шт/кг", "Продано ≈ кг",
                 "Дней с продажами", "Первая продажа", "Последняя продажа"]]

# ---------------------------------------------------------------
# Лист 3: сводка по группам
# ---------------------------------------------------------------
agg["Продано_весовых_кг"] = np.where(agg["Тип"] == "весовой, кг", agg["Продано_ед"], 0.0)
agg["Продано_штучных_шт"] = np.where(agg["Тип"] == "штучный, шт", agg["Продано_ед"], 0.0)
gsum = agg.groupby("группа").agg(
    Товаров=("Код", "count"),
    Выручка_руб=("Выручка_руб", "sum"),
    Продано_весовых_кг=("Продано_весовых_кг", "sum"),
    Продано_штучных_шт=("Продано_штучных_шт", "sum"),
).reset_index()

# лидеры групп
def short(nm, limit=44):
    """Название с многоточием, если длиннее лимита."""
    return nm if len(nm) <= limit else nm[: limit - 1] + "…"

ld_qty = top_qty.sort_values("Место").groupby("группа").first()
ld_rev = top_rev.sort_values("Место").groupby("группа").first()
gsum["Лидер по количеству"] = gsum["группа"].map(
    lambda g: f"{short(ld_qty.loc[g, 'Название'])} — {ld_qty.loc[g, 'Продано_ед']:.0f} {ld_qty.loc[g, 'Тип'].split(', ')[1]}"
)
gsum["Лидер по выручке"] = gsum["группа"].map(
    lambda g: f"{short(ld_rev.loc[g, 'Название'])} — {ld_rev.loc[g, 'Выручка_руб']:,.0f} руб".replace(",", " ")
)

sh_groups = gsum.rename(columns={
    "группа": "Группа",
    "Выручка_руб": "Выручка за всё время, руб",
    "Продано_весовых_кг": "Продано весовых, кг",
    "Продано_штучных_шт": "Продано штучных, шт",
})
sh_groups["Выручка за всё время, руб"] = sh_groups["Выручка за всё время, руб"].round(2)
sh_groups["Продано весовых, кг"] = sh_groups["Продано весовых, кг"].round(1)
sh_groups["Продано штучных, шт"] = sh_groups["Продано штучных, шт"].round(0).astype(int)
sh_groups["Доля в выручке магазина, %"] = (
    sh_groups["Выручка за всё время, руб"] / gsum["Выручка_руб"].sum() * 100
).round(1)
sh_groups = sh_groups.sort_values("Выручка за всё время, руб", ascending=False)

# строка ИТОГО
tot = sh_groups.sum(numeric_only=True)
tot["Группа"] = "ИТОГО по магазину"
tot["Лидер по количеству"] = "—"
tot["Лидер по выручке"] = "—"
sh_groups = pd.concat([sh_groups, tot.to_frame().T], ignore_index=True)

# ---------------------------------------------------------------
# Методика
# ---------------------------------------------------------------
meta = pd.DataFrame([
    ["Период", "Всё время: 2023-01-01 – 2026-08-10 (полный файл продаж)"],
    ["Что показываем", "В каждой группе 5 позиций-лидеров: по количеству (лист 1) и по выручке (лист 2)"],
    ["Единицы количества", "Весовые товары (есть хоть одна дробная продажа, резаная колбаса) — кг; штучные (все продажи целые, упаковки) — штуки; тип указан в колонке «Тип продажи»"],
    ["«Продано ≈ кг»", "Перевод штучных в килограммы: штуки × фасовка из названия (напр. 350г → 0,35 кг); у весовых совпадает с кг; «—» если фасовки в названии нет"],
    ["При равенстве мест", "Сначала идёт позиция с меньшим кодом"],
], columns=["Пункт", "Пояснение"])

# ---------------------------------------------------------------
# Сохранение
# ---------------------------------------------------------------
OUT = "output/Отчет_топ5_колбаса_по_группам.xlsx"
with pd.ExcelWriter(OUT, engine="openpyxl") as writer:
    sh_qty.to_excel(writer, sheet_name="Топ-5_по_количеству", index=False)
    sh_rev.to_excel(writer, sheet_name="Топ-5_по_выручке", index=False)
    sh_groups.to_excel(writer, sheet_name="Сводка_по_группам", index=False)
    meta.to_excel(writer, sheet_name="Методика", index=False)

print(f"\nСохранено: {OUT}")
print("  Листы:", writer.sheets.keys())

# ---------------------------------------------------------------
# Контрольная печать
# ---------------------------------------------------------------
print("\nТОП-5 ПО КОЛИЧЕСТВУ (шт/кг), за всё время:")
for g, grp in sh_qty.groupby("Группа"):
    print(f"— {g}:")
    for _, r in grp.iterrows():
        print(f"   {int(r['Место в группе'])}. {r['Название товара'][:44]:<46} "
              f"{r['Продано за всё время, шт/кг']:>9.1f} {r['Тип продажи'][7:9]} | ≈ {str(r['Продано ≈ кг']):>8} кг | {r['Выручка за всё время, руб']:>12,.0f} руб".replace(",", " "))

print("\nТОП-5 ПО ВЫРУЧКЕ, за всё время:")
for g, grp in sh_rev.groupby("Группа"):
    print(f"— {g}:")
    for _, r in grp.iterrows():
        print(f"   {int(r['Место в группе'])}. {r['Название товара'][:44]:<46} "
              f"{r['Выручка за всё время, руб']:>12,.0f} руб | {r['Продано за всё время, шт/кг']:>9.1f} {r['Тип продажи'][7:9]}".replace(",", " "))

print("\nСводка по группам:")
print(sh_groups.to_string(index=False))
print("\nВсего за всё время: выручка {:.1f} млн руб".format(gsum["Выручка_руб"].sum() / 1e6))
print("Всего за всё время: весовых {:.0f} кг, штучных {:.0f} шт".format(
    gsum["Продано_весовых_кг"].sum(), gsum["Продано_штучных_шт"].sum()))