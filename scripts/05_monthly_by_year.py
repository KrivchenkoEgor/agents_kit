# -*- coding: utf-8 -*-
"""
05_monthly_by_year.py — Помесячный анализ по годам и по каждому товару
======================================================================
Что делает: строит таблицы «год × месяц» и «товар × год × месяц»
и сохраняет их в Excel-книгу output/Молоко_анализ_по_месяцам.xlsx.
Без графиков — только таблицы.

Листы книги:
  1. Свод_по_месяцам   — итоги по каждому месяцу каждого года
  2. Товары_помесячно  — продажи каждого товара по месяцам и годам
  3. Товары_по_годам   — каждый товар одной строкой: продажи по годам
  4. Справочник        — код, название, фасовка, период активности

Внимание к датам: 2026 год неполный (данные до 2026-08-03);
август-2026 помечается как неполный месяц.
"""

import re
from typing import Optional

import pandas as pd

# ---------------------------------------------------------------
# Чтение и подготовка
# ---------------------------------------------------------------
df = pd.read_excel(
    "data/Молоко.xlsx",
    dtype={"Код номенклатуры": str},
    parse_dates=["День"],
)
df["Год"] = df["День"].dt.year
df["Месяц"] = df["День"].dt.month

VOL_PATTERN = re.compile(r"(\d+(?:[.,]\d+)?)\s*(г|мл|л|кг)", re.IGNORECASE)


def parse_volume(name: str) -> Optional[float]:
    m = VOL_PATTERN.search(name)
    if not m:
        return None
    val = float(m.group(1).replace(",", "."))
    unit = m.group(2).lower()
    if unit == "мл":
        return val
    if unit == "л":
        return val * 1000
    if unit == "г":
        return val
    if unit == "кг":
        return val * 1000
    return None


df["Фасовка_г"] = df["Номенклатура"].map(parse_volume)
df["Объём_кг"] = df["ТО, в е.изм."] * df["Фасовка_г"] / 1000

# ---------------------------------------------------------------
# Лист 1: свод по месяцам
# ---------------------------------------------------------------
monthly = (
    df.groupby(["Год", "Месяц"])
    .agg(
        Штук=("ТО, в е.изм.", "sum"),
        Выручка_руб=("ТО, руб", "sum"),
        Объём_кг=("Объём_кг", "sum"),
        Активных_товаров=("Код номенклатуры", "nunique"),
        Дней_с_данными=("День", "nunique"),
    )
    .reset_index()
)

# Полнота месяца: в 2022-2025 по 12 полных месяцев; август-2026 неполный.
# Пометим неполный последний месяц (данные обрываются внутри него).
total_days = df.groupby(["Год", "Месяц"])["День"].nunique()
monthly["Месяц_полный"] = monthly.apply(
    lambda r: total_days.get((r["Год"], r["Месяц"]), 0) >= 28, axis=1
)

# ---------------------------------------------------------------
# Лист 2: товары × месяцы
# ---------------------------------------------------------------
by_sku_month = (
    df.groupby(["Код номенклатуры", "Номенклатура", "Год", "Месяц"])
    .agg(Штук=("ТО, в е.изм.", "sum"), Выручка_руб=("ТО, руб", "sum"))
    .reset_index()
    .sort_values(["Код номенклатуры", "Год", "Месяц"])
)

# ---------------------------------------------------------------
# Лист 3: товары одной строкой — продажи по годам + статус
# ---------------------------------------------------------------
# Статус по периодам янв-июль 2022 и янв-июль 2026 (как в 02/03):
def jan_jul_codes(y: int) -> set:
    m = df[(df["Год"] == y) & (df["Месяц"] <= 7)]
    return set(m["Код номенклатуры"])

set_2022 = jan_jul_codes(2022)
set_2026 = jan_jul_codes(2026)

sku_years = (
    df.groupby(["Код номенклатуры", "Год"])
    .agg(Штук=("ТО, в е.изм.", "sum"), Выручка_руб=("ТО, руб", "sum"))
    .unstack(fill_value=0)
)

codes = sorted(set(df["Код номенклатуры"]))
rows = []
for code in codes:
    first = df[df["Код номенклатуры"] == code]["День"].min().date()
    last = df[df["Код номенклатуры"] == code]["День"].max().date()
    if code in set_2022 and code in set_2026:
        status = "остался"
    elif code in set_2022:
        status = "ушёл"
    else:
        status = "пришёл"
    r = {
        "Код": code,
        "Название": df[df["Код номенклатуры"] == code]["Номенклатура"].iloc[0],
        "Фасовка_г": df[df["Код номенклатуры"] == code]["Фасовка_г"].iloc[0],
        "Статус": status,
        "Первый_день": first,
        "Последний_день": last,
    }
    total_q = int(df[df["Код номенклатуры"] == code]["ТО, в е.изм."].sum())
    total_rub = float(df[df["Код номенклатуры"] == code]["ТО, руб"].sum())
    r["Всего_шт"] = total_q
    r["Всего_руб"] = round(total_rub, 2)
    rows.append(r)

sku_by_year = pd.DataFrame(rows)
# добавим по-годичные столбцы аккуратно (через pivot)
pivot_q = (
    df.pivot_table(index="Код номенклатуры", columns="Год", values="ТО, в е.изм.", aggfunc="sum", fill_value=0)
)
pivot_rub = (
    df.pivot_table(index="Код номенклатуры", columns="Год", values="ТО, руб", aggfunc="sum", fill_value=0)
)
for y in pivot_q.columns:
    sku_by_year[f"{y}_шт"] = sku_by_year["Код"].map(pivot_q[y])
    sku_by_year[f"{y}_руб"] = sku_by_year["Код"].map(pivot_rub[y]).round(2)

# порядок колонок: Код, Название, Фасовка, Статус, годы (шт, руб), всего
year_cols = []
for y in sorted(pivot_q.columns):
    year_cols += [f"{y}_шт", f"{y}_руб"]
cols = ["Код", "Название", "Фасовка_г", "Статус", "Первый_день", "Последний_день"] + year_cols + ["Всего_шт", "Всего_руб"]
sku_by_year = sku_by_year[cols]

# ---------------------------------------------------------------
# Лист 4: справочник
# ---------------------------------------------------------------
catalog = (
    df.groupby("Код номенклатуры")
    .agg(
        Название=("Номенклатура", "first"),
        Фасовка_г=("Фасовка_г", "first"),
        Первый_день=("День", "min"),
        Последний_день=("День", "max"),
        Дней_с_продажами=("День", "nunique"),
        Записей=("День", "size"),
    )
    .reset_index()
)

# ---------------------------------------------------------------
# Контрольная сверка (было/стало)
# ---------------------------------------------------------------
total_q = df["ТО, в е.изм."].sum()
total_rub = df["ТО, руб"].sum()
sum_q = by_sku_month["Штук"].sum()
sum_rub = by_sku_month["Выручка_руб"].sum()
assert abs(sum_q - total_q) < 1, "Штуки не сходятся!"
assert abs(sum_rub - total_rub) < 0.01, "Выручка не сходится!"

# ---------------------------------------------------------------
# Сохранение книги
# ---------------------------------------------------------------
# Понятные заголовки колонок: сущность + единица измерения
R = {
    "Код номенклатуры": "Код товара",
    "Номенклатура": "Название товара",
    "Штук": "Продано, штук",
    "Выручка_руб": "Выручка, руб",
    "Объём_кг": "Продано, кг",
    "Активных_товаров": "Товаров в продаже",
    "Дней_с_данными": "Дней с продажами",
    "Месяц_полный": "Месяц полный",
    "Код": "Код товара",
    "Название": "Название товара",
    "Фасовка_г": "Фасовка, г/мл",
    "Статус": "Статус",
    "Первый_день": "Первая продажа",
    "Последний_день": "Последняя продажа",
    "Всего_шт": "Продано всего, штук",
    "Всего_руб": "Выручка всего, руб",
    "Дней_с_продажами": "Дней с продажами",
    "Записей": "Записей о продажах",
}
for y in pivot_q.columns:
    R[f"{y}_шт"] = f"Продано {y}, штук"
    R[f"{y}_руб"] = f"Выручка {y}, руб"

OUT = "output/Молоко_анализ_по_месяцам.xlsx"
with pd.ExcelWriter(OUT, engine="openpyxl") as writer:
    monthly.rename(columns=R).to_excel(writer, sheet_name="Свод_по_месяцам", index=False)
    by_sku_month.rename(columns=R).to_excel(writer, sheet_name="Товары_помесячно", index=False)
    sku_by_year.rename(columns=R).to_excel(writer, sheet_name="Товары_по_годам", index=False)
    catalog.rename(columns=R).to_excel(writer, sheet_name="Справочник", index=False)

print(f"Книга сохранена: {OUT}")
print(f"Лист «Свод_по_месяцам»: {len(monthly)} строк (месяцев)")
print(f"Лист «Товары_помесячно»: {len(by_sku_month)} строк (товар × месяц)")
print(f"Лист «Товары_по_годам»: {len(sku_by_year)} строк (товаров)")
print(f"Лист «Справочник»: {len(catalog)} строк (товаров)")
print()
print("КОНТРОЛЬНАЯ СВЕРКА:")
print(f"  Штук по исходнику: {total_q:,.0f}  |  по таблицам: {sum_q:,.0f}  — совпадает: {abs(sum_q - total_q) < 1}".replace(",", " "))
print(f"  Выручка по исходнику: {total_rub:,.2f}  |  по таблицам: {sum_rub:,.2f}  — совпадает: {abs(sum_rub - total_rub) < 0.01}".replace(",", " "))
