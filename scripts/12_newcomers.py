# -*- coding: utf-8 -*-
"""
12_newcomers.py — Судьба новинок: кто пришёл в ассортимент и что из них вышло
=============================================================================
Новинка = «история» товара, которой не было в 2022 году
(первая продажа позже 2022-12-31). Смотрим, что с новинками стало:
продаются ли до сих пор, до какого статуса выросли (A/B/C по выручке
за последние 12 полных месяцев), какой пик продаж имели и где сейчас.

Выход: output/Новинки_судьба.xlsx + печать в консоль.
"""

import pandas as pd

# ---------------------------------------------------------------
# Чтение и склейка в истории (как в 10)
# ---------------------------------------------------------------
df = pd.read_excel(
    "data/Молоко.xlsx",
    dtype={"Код номенклатуры": str},
    parse_dates=["День"],
)
pairs = pd.read_excel("output/пары_шринкфляции.xlsx", dtype=str)

chain_map = {}
for _, p in pairs.iterrows():
    chain_map[p["Код старой упаковки"]] = p["Код старой упаковки"]
    chain_map[p["Код новой упаковки"]] = p["Код старой упаковки"]
for code in df["Код номенклатуры"].unique():
    chain_map.setdefault(code, code)

df["История"] = df["Код номенклатуры"].map(chain_map)
df["Год"] = df["День"].dt.year
df["Месяц"] = df["День"].dt.month

chain_names = {}
for _, p in pairs.iterrows():
    chain_names[p["Код старой упаковки"]] = (
        f"{p['Название старой упаковки'][:38]} → {p['Название новой упаковки'][:38]}"
    )
first_name = df.groupby("Код номенклатуры")["Номенклатура"].first().to_dict()


def history_label(h: str) -> str:
    return chain_names.get(h, first_name[h])


recent = df[(df["День"] >= "2025-08-01") & (df["День"] <= "2026-07-31")]

# ---------------------------------------------------------------
# Новинки: первая продажа истории позже 2022 года
# ---------------------------------------------------------------
first_sale = df.groupby("История")["День"].min()
last_sale = df.groupby("История")["День"].max()

newcomers = first_sale[first_sale > pd.Timestamp("2022-12-31")]
print("=" * 78)
print(f"НОВИНОК (появились после 2022 года): {len(newcomers)} из "
      f"{len(first_sale)} историй".replace(",", " "))
print("=" * 78)

# ---------------------------------------------------------------
# Группа ABC по выручке за последние 12 мес (для всех историй)
# ---------------------------------------------------------------
g = recent.groupby("История")["ТО, руб"].sum().sort_values(ascending=False)
g = g[g > 0]
cum = g.cumsum() / g.sum()
group = pd.Series("C", index=g.index)
group[cum <= 0.80] = "A"
group[(cum > 0.80) & (cum <= 0.95)] = "B"

# ---------------------------------------------------------------
# Детали по каждой новинке
# ---------------------------------------------------------------
per_hist = recent.groupby("История").agg(
    Выручка=("ТО, руб", "sum"),
    Штук=("ТО, в е.изм.", "sum"),
)

rows = []
for h in newcomers.index:
    first = first_sale[h]
    last = last_sale[h]
    alive = last >= pd.Timestamp("2026-02-01")  # продавалась в последние полгода
    rub = per_hist.loc[h, "Выручка"] if h in per_hist.index else 0.0
    qty = per_hist.loc[h, "Штук"] if h in per_hist.index else 0.0
    grp = group.get(h, "—")
    # пик продаж (штук/мес) и «сейчас vs пик»
    hm = df[df["История"] == h].groupby(["Год", "Месяц"])["ТО, в е.изм."].sum()
    if len(hm):
        peak_idx = hm.idxmax()
        peak = float(hm.max())
        peak_label = f"{peak_idx[0]}-{peak_idx[1]:02d}"
        cur3 = df[(df["История"] == h) & (df["День"] >= "2026-05-01") & (df["День"] <= "2026-07-31")]["ТО, в е.изм."].sum()
        vs_peak = (cur3 / 3) / peak * 100 if peak > 0 else None
    else:
        peak, peak_label, vs_peak = None, None, None
    rows.append(
        {
            "Название товара (история)": history_label(h),
            "Код истории": h,
            "Год появления": first.year,
            "Первая продажа": first.date(),
            "Последняя продажа": last.date(),
            "Статус сейчас": "продаётся" if alive else "не продаётся",
            "Группа ABC сейчас": grp,
            "Выручка за 12 мес, руб": round(rub, 2),
            "Продано за 12 мес, штук": int(qty),
            "Пик продаж, штук/мес": peak,
            "Месяц пика": peak_label,
            "Сейчас vs пик, %": round(vs_peak, 1) if vs_peak is not None else None,
        }
    )

tbl = pd.DataFrame(rows).sort_values(
    ["Год появления", "Выручка за 12 мес, руб"], ascending=[True, False]
)

# ---------------------------------------------------------------
# Сводка по годам появления
# ---------------------------------------------------------------
summary = (
    tbl.groupby("Год появления")
    .agg(
        Новинок=("Название товара (история)", "size"),
        Продаются_сейчас=("Статус сейчас", lambda s: (s == "продаётся").sum()),
        Стали_A=("Группа ABC сейчас", lambda s: (s == "A").sum()),
        Стали_B=("Группа ABC сейчас", lambda s: (s == "B").sum()),
        Остались_C=("Группа ABC сейчас", lambda s: (s == "C").sum()),
        Выручка_руб=("Выручка за 12 мес, руб", "sum"),
        Штук=("Продано за 12 мес, штук", "sum"),
    )
    .reset_index()
)
summary["Доля живых, %"] = summary["Продаются_сейчас"] / summary["Новинок"] * 100
summary = summary.rename(
    columns={
        "Новинок": "Новинок, шт",
        "Продаются_сейчас": "Продаются сейчас, шт",
        "Стали_A": "Стали звёздами (A), шт",
        "Стали_B": "Стали середняками (B), шт",
        "Остались_C": "Остались тихонями (C), шт",
        "Выручка_руб": "Выручка за 12 мес, руб",
        "Штук": "Продано за 12 мес, штук",
    }
)

print("\nСводка по году появления:")
print(summary.to_string(index=False))

print("\nКаждая новинка (сначала старые новинки, потом свежие):")
for _, r in tbl.iterrows():
    vs = f"  сейчас {r['Сейчас vs пик, %']:.0f}% от пика" if pd.notna(r["Сейчас vs пик, %"]) else ""
    print(f"  {r['Год появления']}  [{r['Группа ABC сейчас']}]  {r['Выручка за 12 мес, руб']:>9,.0f} руб  "
          f"{r['Продано за 12 мес, штук']:>5,} шт  {r['Статус сейчас']}{vs}  "
          f"{r['Название товара (история)'][:45]}".replace(",", " "))

# ---------------------------------------------------------------
# Сохранение книги
# ---------------------------------------------------------------
OUT = "output/Новинки_судьба.xlsx"
with pd.ExcelWriter(OUT, engine="openpyxl") as writer:
    summary.to_excel(writer, sheet_name="Новинки_по_годам", index=False)
    tbl.to_excel(writer, sheet_name="Каждая_новинка", index=False)

print(f"\nСохранено: {OUT}")
print("  Лист «Новинки_по_годам»:", len(summary), "лет")
print("  Лист «Каждая_новинка»:", len(tbl), "новинок")
