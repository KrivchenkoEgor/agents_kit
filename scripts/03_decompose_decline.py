# -*- coding: utf-8 -*-
"""
03_decompose_decline.py — Разложение падения продаж на факторы
===============================================================
Вопрос: почему продажи в штуках упали вдвое (2022 → 2026)?

Идея: представить падение как сумму трёх составляющих —
  1) ушедшие товары (их продажи в 2022 мы потеряли),
  2) пришедшие товары (их продажи в 2026 мы получили),
  3) оставшиеся товары (у них продажи могли упасть или вырасти).

Сравниваем ТОЛЬКО одинаковые периоды: январь–июль 2022 и январь–июль 2026
(оба полные; август-2026 неполный и не участвует).

Дополнительно считаем «физический объём»: штуки × фасовка в граммах.
Если фасовка уменьшилась (шринкфляция: было 950г, стало 850мл), то при
том же числе упаковок объём молока падает.

Вход:  data/Молоко.xlsx
Выход: печать отчёта в консоль
"""

import re
from typing import Optional

import pandas as pd

# ---------------------------------------------------------------
# Чтение и подготовка
# ---------------------------------------------------------------
df = pd.read_excel(
    "data/Молоко.xlsx",
    dtype={"Код номенклатуры": str},
    parse_dates=["День"],
)
df["Год"] = df["День"].dt.year
df["Месяц"] = df["День"].dt.month

# Фасовка из названия (в граммах, 1 мл ≈ 1 г для молока)
VOL_PATTERN = re.compile(r"(\d+(?:[.,]\d+)?)\s*(г|мл|л|кг)", re.IGNORECASE)


def parse_volume(name: str) -> Optional[float]:
    m = VOL_PATTERN.search(name)
    if not m:
        return None
    val = float(m.group(1).replace(",", "."))
    unit = m.group(2).lower()
    if unit == "мл":
        return val
    if unit == "л":
        return val * 1000
    if unit == "г":
        return val
    if unit == "кг":
        return val * 1000
    return None


df["Фасовка_г"] = df["Номенклатура"].map(parse_volume)
# Физический объём проданного молока: упаковки × граммов в упаковке
df["Объём_г"] = df["ТО, в е.изм."] * df["Фасовка_г"]

# ---------------------------------------------------------------
# Периоды сравнения (одинаковые: январь-июль)
# ---------------------------------------------------------------
def jan_jul(y: int) -> pd.DataFrame:
    return df[(df["Год"] == y) & (df["Месяц"] <= 7)]

a = jan_jul(2022)   # «было»
b = jan_jul(2026)   # «стало»

print("=" * 70)
print("1. ИТОГ ПО ПЕРИОДАМ (январь–июль)")
print("=" * 70)

def totals(d: pd.DataFrame) -> dict:
    return {
        "штук": int(d["ТО, в е.изм."].sum()),
        "объём_кг": float(d["Объём_г"].sum()) / 1000,
        "выручка": float(d["ТО, руб"].sum()),
    }

ta, tb = totals(a), totals(b)
print(f"{'':14}{'2022 янв-июль':>18}{'2026 янв-июль':>18}{'изменение':>12}")
for key, label in [("штук", "Штук (упаковок)"), ("объём_кг", "Объём, кг"), ("выручка", "Выручка, руб")]:
    va, vb = ta[key], tb[key]
    print(f"{label:14}{va:>18,.0f}{vb:>18,.0f}{vb / va - 1:>+12.1%}".replace(",", " "))

# ---------------------------------------------------------------
# 2. Разложение по группам: ушедшие / пришедшие / оставшиеся
# ---------------------------------------------------------------
print("\n" + "=" * 70)
print("2. РАЗЛОЖЕНИЕ ПО ГРУППАМ ТОВАРОВ (штуки, янв-июль)")
print("=" * 70)

codes_a, codes_b = set(a["Код номенклатуры"]), set(b["Код номенклатуры"])
gone = codes_a - codes_b        # были в 2022, нет в 2026
arrived = codes_b - codes_a     # нет в 2022, есть в 2026
stayed = codes_a & codes_b      # есть в обоих

groups = {
    "Ушедшие (потеря)": a[a["Код номенклатуры"].isin(gone)],
    "Пришедшие (прибавка)": b[b["Код номенклатуры"].isin(arrived)],
    "Оставшиеся 2022": a[a["Код номенклатуры"].isin(stayed)],
    "Оставшиеся 2026": b[b["Код номенклатуры"].isin(stayed)],
}

for name, g in groups.items():
    qty = g["ТО, в е.изм."].sum()
    vol = g["Объём_г"].sum() / 1000
    rub = g["ТО, руб"].sum()
    print(f"{name:22} штук {qty:>9,.0f}   объём {vol:>10,.0f} кг   выручка {rub:>12,.0f} руб".replace(",", " "))

# Баланс штук: было = ушедшие + оставшиеся-2022; стало = пришедшие + оставшиеся-2026
loss_gone = groups["Ушедшие (потеря)"]["ТО, в е.изм."].sum()
gain_arrived = groups["Пришедшие (прибавка)"]["ТО, в е.изм."].sum()
q_old_stay = groups["Оставшиеся 2022"]["ТО, в е.изм."].sum()
q_new_stay = groups["Оставшиеся 2026"]["ТО, в е.изм."].sum()

print("\nБаланс штук:")
print(f"  Было (2022):       {ta['штук']:>9,.0f}".replace(",", " "))
print(f"  Ушло вместе с товарами: -{loss_gone:,.0f}".replace(",", " "))
print(f"  Пришло с новыми:       +{gain_arrived:,.0f}".replace(",", " "))
print(f"  Оставшиеся потеряли:   -{q_old_stay - q_new_stay:,.0f}".replace(",", " "))
print(f"  Стало (2026):      {tb['штук']:>9,.0f}".replace(",", " "))

# ---------------------------------------------------------------
# 3. Оставшиеся товары: кто упал, кто вырос
# ---------------------------------------------------------------
print("\n" + "=" * 70)
print("3. ОСТАВШИЕСЯ 26 ТОВАРОВ: ИЗМЕНЕНИЕ ПРОДАЖ")
print("=" * 70)

names = df.groupby("Код номенклатуры")["Номенклатура"].first()
rows = []
for code in sorted(stayed):
    qa = a[a["Код номенклатуры"] == code]["ТО, в е.изм."].sum()
    qb = b[b["Код номенклатуры"] == code]["ТО, в е.изм."].sum()
    rows.append((code, qa, qb, qb / qa - 1 if qa else None, names[code]))

# Худшие (наибольшая потеря штук в абсолютных значениях)
print("\nХудшие — потеряли больше всего штук:")
for code, qa, qb, chg, nm in sorted(rows, key=lambda r: r[1] - r[2], reverse=True)[:8]:
    print(f"  {qa - qb:>8,.0f} шт ({chg:+.0%})  {nm[:65]}".replace(",", " "))

print("\nЛучшие — выросли:")
for code, qa, qb, chg, nm in sorted(rows, key=lambda r: r[2] - r[1], reverse=True)[:5]:
    print(f"  +{qb - qa:>7,.0f} шт ({chg:+.0%})  {nm[:65]}".replace(",", " "))

# ---------------------------------------------------------------
# 4. Эффект шринкфляции: средняя фасовка и цена
# ---------------------------------------------------------------
print("\n" + "=" * 70)
print("4. ФАСОВКИ И ЦЕНЫ: ЧТО ПРОИЗОШЛО С ТОВАРОМ")
print("=" * 70)

avg_vol_a = a["Объём_г"].sum() / a["ТО, в е.изм."].sum()
avg_vol_b = b["Объём_г"].sum() / b["ТО, в е.изм."].sum()
print(f"Средняя фасовка проданной упаковки: 2022 — {avg_vol_a:.0f} г, 2026 — {avg_vol_b:.0f} г "
      f"({avg_vol_b / avg_vol_a - 1:+.1%})".replace(",", " "))

price_a = a["ТО, руб"].sum() / a["ТО, в е.изм."].sum()
price_b = b["ТО, руб"].sum() / b["ТО, в е.изм."].sum()
print(f"Средняя цена упаковки: 2022 — {price_a:.2f} руб, 2026 — {price_b:.2f} руб "
      f"({price_b / price_a - 1:+.1%})".replace(",", " "))

price_per_kg_a = a["ТО, руб"].sum() / (a["Объём_г"].sum() / 1000)
price_per_kg_b = b["ТО, руб"].sum() / (b["Объём_г"].sum() / 1000)
print(f"Цена за кг молока: 2022 — {price_per_kg_a:.2f} руб/кг, 2026 — {price_per_kg_b:.2f} руб/кг "
      f"({price_per_kg_b / price_per_kg_a - 1:+.1%})".replace(",", " "))

# Сравним среднюю фасовку у ОСТАВШИХСЯ (там фасовка по коду стабильна — проверим)
print("\nПроверка фасовки у оставшихся товаров (не менялась ли):")
stable = True
for code in stayed:
    vols = df[df["Код номенклатуры"] == code]["Фасовка_г"].unique()
    if len(vols) > 1:
        stable = False
        print(f"  Код {code}: фасовки менялись: {vols}")
if stable:
    print("  У всех 26 оставшихся фасовка по коду стабильна (смены нет).")

print("\n" + "=" * 70)
print("Декомпозиция завершена.")
print("=" * 70)
