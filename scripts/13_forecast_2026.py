# -*- coding: utf-8 -*-
"""
13_forecast_2026.py — Прогноз на остаток 2026 (август–декабрь)
===============================================================
Идея: продажи = тренд (куда движется магазин) × сезонность
(летом молока пьют больше, зимой меньше). План:
  1) сезонные коэффициенты месяца — по полным годам 2022–2025;
  2) очищаем помесячный ряд от сезонности;
  3) линейный тренд — по последним 18 полным месяцам
     (ближняя динамика важнее далёкой истории);
  4) прогноз = тренд × сезонность, с 95% доверительным интервалом
     (предикционный интервал линейной регрессии).

Честно: это экстраполяция, а не предсказание. Если магазин изменит
ассортимент или цены, придут конкуренты — факт разойдётся с прогнозом.

Выход: output/Прогноз_2026.xlsx + печать в консоль.
"""

import re

import numpy as np
import pandas as pd

# ---------------------------------------------------------------
# Чтение и помесячные итоги
# ---------------------------------------------------------------
df = pd.read_excel(
    "data/Молоко.xlsx",
    dtype={"Код номенклатуры": str},
    parse_dates=["День"],
)
df["Год"] = df["День"].dt.year
df["Месяц"] = df["День"].dt.month

# Фасовка — нужна для цены за кг (контекст в модели)
VOL_PATTERN = re.compile(r"(\d+(?:[.,]\d+)?)\s*(г|мл|л|кг)", re.IGNORECASE)


def parse_volume(name: str):
    m = VOL_PATTERN.search(name)
    if not m:
        return None
    val = float(m.group(1).replace(",", "."))
    unit = m.group(2).lower()
    if unit == "мл":
        return val
    if unit == "л":
        return val * 1000
    if unit == "г":
        return val
    if unit == "кг":
        return val * 1000
    return None


df["Фасовка_г"] = df["Номенклатура"].map(parse_volume)
df["Объём_кг"] = df["ТО, в е.изм."] * df["Фасовка_г"] / 1000

days_in_month = df.groupby(["Год", "Месяц"])["День"].nunique()
monthly = (
    df.groupby(["Год", "Месяц"])
    .agg(
        Штук=("ТО, в е.изм.", "sum"),
        Выручка=("ТО, руб", "sum"),
        Объём_кг=("Объём_кг", "sum"),
    )
    .reset_index()
)
monthly["Дней_с_данными"] = monthly.apply(
    lambda r: days_in_month.get((r["Год"], r["Месяц"]), 0), axis=1
)

# В модель берём только ПОЛНЫЕ месяцы (август-2026 неполный: 3 дня)
full = (
    monthly[monthly["Дней_с_данными"] >= 28]
    .sort_values(["Год", "Месяц"])
    .reset_index(drop=True)
)
full["t"] = np.arange(len(full))

# ---------------------------------------------------------------
# Сезонность: доля месяца в среднем по году, усреднённая по годам
# ---------------------------------------------------------------
full["Выручка_доля_года"] = full["Выручка"] / full.groupby("Год")["Выручка"].transform("mean")
full["Штук_доля_года"] = full["Штук"] / full.groupby("Год")["Штук"].transform("mean")
season = full.groupby("Месяц")[["Выручка_доля_года", "Штук_доля_года"]].mean()

full["Выручка_без_сезонности"] = full["Выручка"] / full["Месяц"].map(season["Выручка_доля_года"])
full["Штук_без_сезонности"] = full["Штук"] / full["Месяц"].map(season["Штук_доля_года"])

MONTHS_RU = ["янв", "фев", "мар", "апр", "май", "июн", "июл", "авг", "сен", "окт", "ноя", "дек"]

# ---------------------------------------------------------------
# Прогноз: тренд по последним 18 полным месяцам × сезонность
# ---------------------------------------------------------------
W = 18
tail = full.tail(W)
t_tail = tail["t"].values
xbar = t_tail.mean()
sxx = np.sum((t_tail - xbar) ** 2)

forecast_rows = []
for m in range(8, 13):  # август … декабрь
    t_f = full["t"].max() + (m - 7)  # авг = последний месяц + 1, дек = +5
    out = {"Месяц": f"{MONTHS_RU[m - 1]} 2026"}
    for label, col_adj, col_season in [
        ("Выручка", "Выручка_без_сезонности", "Выручка_доля_года"),
        ("Штук", "Штук_без_сезонности", "Штук_доля_года"),
    ]:
        # ВАЖНО: polyfit возвращает [старшая степень … младшая] →
        # для прямой это [наклон, свободный член], не наоборот!
        slope, inter = np.polyfit(np.arange(W), tail[col_adj].values, 1)
        fitted = inter + slope * np.arange(W)
        resid = tail[col_adj].values - fitted
        s = np.sqrt(np.sum(resid ** 2) / (W - 2))  # остаточный разброс
        pred_adj = inter + slope * (t_f - tail["t"].iloc[0])
        se = s * np.sqrt(1 + 1 / W + (t_f - xbar) ** 2 / sxx)  # 95% интервал
        fc = pred_adj * season.loc[m, col_season]
        lo = (pred_adj - 1.96 * se) * season.loc[m, col_season]
        hi = (pred_adj + 1.96 * se) * season.loc[m, col_season]
        out[label] = round(fc, 2)
        out[label + "_низ"] = round(max(lo, 0), 2)
        out[label + "_верх"] = round(hi, 2)
    forecast_rows.append(out)

fc = pd.DataFrame(forecast_rows)
fc["Выручка"] = fc["Выручка"].round(0)
fc["Выручка_низ"] = fc["Выручка_низ"].round(0)
fc["Выручка_верх"] = fc["Выручка_верх"].round(0)
fc["Штук"] = fc["Штук"].round(0)
fc["Штук_низ"] = fc["Штук_низ"].round(0)
fc["Штук_верх"] = fc["Штук_верх"].round(0)

# ---------------------------------------------------------------
# Сравнение с тем же периодом 2025
# ---------------------------------------------------------------
y25 = monthly[(monthly["Год"] == 2025) & (monthly["Месяц"] >= 8)]
sum25_r = y25["Выручка"].sum()
sum25_q = y25["Штук"].sum()
sum_fc_r = fc["Выручка"].sum()
sum_fc_q = fc["Штук"].sum()

print("=" * 78)
print("ПРОГНОЗ НА АВГУСТ–ДЕКАБРЬ 2026 (тренд × сезонность, 95% интервал)")
print("=" * 78)
for _, r in fc.iterrows():
    print(f"  {r['Месяц']:<10} выручка {r['Выручка']:>10,.0f} руб "
          f"({r['Выручка_низ']:>9,.0f}…{r['Выручка_верх']:>9,.0f})  "
          f"штук {r['Штук']:>6,.0f} ({r['Штук_низ']:>5,.0f}…{r['Штук_верх']:>5,.0f})".replace(",", " "))

print(f"\nАвг–дек 2025 (факт):   выручка {sum25_r:>12,.0f} руб, штук {sum25_q:>8,.0f}".replace(",", " "))
print(f"Авг–дек 2026 (прогноз): выручка {sum_fc_r:>12,.0f} руб, штук {sum_fc_q:>8,.0f}".replace(",", " "))
print(f"  ожидаемое изменение: выручка {sum_fc_r / sum25_r - 1:+.1%}, "
      f"штуки {sum_fc_q / sum25_q - 1:+.1%}".replace(",", " "))

# ---------------------------------------------------------------
# Проверка: август-2026 (3 дня факта) против прогноза
# ---------------------------------------------------------------
aug = df[(df["Год"] == 2026) & (df["Месяц"] == 8)]
n_days = aug["День"].nunique()
q_aug, r_aug = aug["ТО, в е.изм."].sum(), aug["ТО, руб"].sum()
ext_q, ext_r = q_aug * 31 / n_days, r_aug * 31 / n_days
fc_aug = fc[fc["Месяц"] == "авг 2026"].iloc[0]

print("\n" + "=" * 78)
print(f"ПРОВЕРКА НА АВГУСТЕ-2026: факт {n_days} дня ({aug['День'].min().date()}…{aug['День'].max().date()})")
print("=" * 78)
print(f"  Выручка: факт {r_aug:,.0f} руб → экстраполяция на месяц ≈ {ext_r:,.0f} "
      f"vs прогноз {fc_aug['Выручка']:,.0f} руб ({ext_r / fc_aug['Выручка'] - 1:+.0%})".replace(",", " "))
print(f"  Штук:    факт {q_aug:,.0f} шт → экстраполяция на месяц ≈ {ext_q:,.0f} "
      f"vs прогноз {fc_aug['Штук']:,.0f} шт ({ext_q / fc_aug['Штук'] - 1:+.0%})".replace(",", " "))
print("  (экстраполяция грубая: начало месяца может отличаться от середины)")

# ---------------------------------------------------------------
# Сохранение книги
# ---------------------------------------------------------------
model_sheet = full.copy()
model_sheet = model_sheet.drop(columns=["t"])  # технический индекс — в отчёт не нужен
model_sheet["Месяц"] = model_sheet["Месяц"].map(lambda m: MONTHS_RU[m - 1])
model_sheet = model_sheet.rename(
    columns={
        "Год": "Год",
        "Месяц": "Месяц",
        "Штук": "Продано, штук (факт)",
        "Выручка": "Выручка, руб (факт)",
        "Объём_кг": "Продано, кг (факт)",
        "Дней_с_данными": "Дней с продажами",
        "Выручка_доля_года": "Сезонный коэффициент выручки",
        "Штук_доля_года": "Сезонный коэффициент штук",
        "Выручка_без_сезонности": "Выручка без сезонности, руб",
        "Штук_без_сезонности": "Штук без сезонности",
    }
)
model_sheet["Цена за штуку, руб"] = (model_sheet["Выручка, руб (факт)"] / model_sheet["Продано, штук (факт)"]).round(2)
model_sheet["Цена за кг, руб"] = (model_sheet["Выручка, руб (факт)"] / model_sheet["Продано, кг (факт)"]).round(2)

fc_sheet = fc.rename(
    columns={
        "Месяц": "Месяц",
        "Выручка": "Прогноз выручки, руб",
        "Выручка_низ": "Нижняя граница (95%), руб",
        "Выручка_верх": "Верхняя граница (95%), руб",
        "Штук": "Прогноз штук",
        "Штук_низ": "Нижняя граница штук",
        "Штук_верх": "Верхняя граница штук",
    }
)

check = pd.DataFrame(
    {
        "Показатель": ["Выручка, руб", "Продано, штук"],
        "Факт за 3 дня августа": [round(r_aug, 2), int(q_aug)],
        "Экстраполяция на месяц": [round(ext_r, 0), round(ext_q, 0)],
        "Прогноз модели на август": [fc_aug["Выручка"], fc_aug["Штук"]],
        "Расхождение, %": [
            round(ext_r / fc_aug["Выручка"] - 1, 3),
            round(ext_q / fc_aug["Штук"] - 1, 3),
        ],
    }
)

OUT = "output/Прогноз_2026.xlsx"
with pd.ExcelWriter(OUT, engine="openpyxl") as writer:
    fc_sheet.to_excel(writer, sheet_name="Прогноз_авг_дек", index=False)
    model_sheet.to_excel(writer, sheet_name="Модель_помесячно", index=False)
    check.to_excel(writer, sheet_name="Проверка_август", index=False)

print(f"\nСохранено: {OUT}")
print("  Лист «Прогноз_авг_дек»:", len(fc_sheet), "месяцев")
print("  Лист «Модель_помесячно»:", len(model_sheet), "полных месяцев")
print("  Лист «Проверка_август»: 2 строки")
