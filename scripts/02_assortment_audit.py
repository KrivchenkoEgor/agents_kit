# -*- coding: utf-8 -*-
"""
02_assortment_audit.py — Аудит ассортимента: кто менялся, кто ушёл, кто пришёл
=============================================================================
Задача: понять, как менялся ассортимент во времени.
Особое внимание — «шринкфляции»: товар мог продаваться в одной фасовке
в 2022 году и в другой (меньшей) в 2026, при том же коде или названии.

Вход:  data/Молоко.xlsx
Выход: печать отчёта в консоль
"""

import re
from typing import Optional

import pandas as pd

# ---------------------------------------------------------------
# Чтение (коды — текст, даты — настоящие даты)
# ---------------------------------------------------------------
df = pd.read_excel(
    "data/Молоко.xlsx",
    dtype={"Код номенклатуры": str},
    parse_dates=["День"],
)
df["Год"] = df["День"].dt.year

# ---------------------------------------------------------------
# 1. Один код — несколько названий? (признак смены фасовки/брендинга)
# ---------------------------------------------------------------
print("=" * 70)
print("1. КОДЫ С НЕСКОЛЬКИМИ НАЗВАНИЯМИ (признак изменений)")
print("=" * 70)

name_counts = df.groupby("Код номенклатуры")["Номенклатура"].nunique()
multi_codes = name_counts[name_counts > 1]
print(f"Кодов, у которых встречается больше одного названия: {len(multi_codes)} из {df['Код номенклатуры'].nunique()}")

for code in multi_codes.index:
    g = (
        df[df["Код номенклатуры"] == code]
        .groupby("Номенклатура")
        .agg(
            период_с=("День", "min"),
            период_по=("День", "max"),
            записей=("День", "size"),
        )
    )
    print(f"\nКод {code}:")
    for name, row in g.iterrows():
        print(f"  [{row['период_с'].date()} — {row['период_по'].date()}, {row['записей']} зап.] {name}")

# ---------------------------------------------------------------
# 2. Извлечение фасовки (объёма) из названия
# ---------------------------------------------------------------
# Регулярное выражение ищет число + единицу: 950г, 950мл, 2000г, 2кг...
# Приводим всё к «граммам» (для молока 1 мл ≈ 1 г — допустимо для сравнения).
VOL_PATTERN = re.compile(r"(\d+(?:[.,]\d+)?)\s*(г|мл|л|кг)", re.IGNORECASE)


def parse_volume(name: str) -> Optional[float]:
    """Возвращает объём в граммах или None, если фасовки в названии нет."""
    m = VOL_PATTERN.search(name)
    if not m:
        return None
    val = float(m.group(1).replace(",", "."))
    unit = m.group(2).lower()
    if unit == "мл":
        return val          # 1 мл ≈ 1 г для молока
    if unit == "л":
        return val * 1000
    if unit == "г":
        return val
    if unit == "кг":
        return val * 1000
    return None


df["Объём_г"] = df["Номенклатура"].map(parse_volume)
no_volume = df["Объём_г"].isna()
print("\n" + "=" * 70)
print("2. ФАСОВКИ В НАЗВАНИЯХ")
print("=" * 70)
print(f"Записей, где фасовку НЕ удалось извлечь: {no_volume.sum()} из {len(df)}")
if no_volume.any():
    print("Примеры названий без фасовки:")
    for n in df.loc[no_volume, "Номенклатура"].unique()[:10]:
        print(f"  {n}")

# ---------------------------------------------------------------
# 3. Менялась ли фасовка у одного кода по годам? (шринкфляция)
# ---------------------------------------------------------------
print("\n" + "=" * 70)
print("3. ИЗМЕНЕНИЕ ФАСОВКИ У ОДНОГО КОДА ПО ГОДАМ")
print("=" * 70)

vol_by_year = (
    df.dropna(subset=["Объём_г"])
    .groupby(["Код номенклатуры", "Год"])["Объём_г"]
    .unique()
)
shrink = []
for (code, year), vols in vol_by_year.items():
    if len(vols) > 1:
        shrink.append((code, year, vols))

if shrink:
    print(f"Кодов, у которых в одном году встречаются разные фасовки: {len(shrink)}")
    for code, year, vols in shrink[:15]:
        print(f"  Код {code}, {year}: фасовки {sorted(vols)}")
else:
    print("Таких случаев нет.")

# ---------------------------------------------------------------
# 4. В чём измеряется «ТО, в е.изм.»: штуки или литры?
#    Тест: если это ШТУКИ упаковок — цена за единицу растёт с объёмом
#    фасовки (больше упаковка — дороже). Если ЛИТРЫ — цена за единицу
#    примерно одинаковая у разных фасовок.
# ---------------------------------------------------------------
print("\n" + "=" * 70)
print("4. ЧТО ТАКОЕ «ЕДИНИЦА ИЗМЕРЕНИЯ»: ШТУКИ ИЛИ ЛИТРЫ/КГ?")
print("=" * 70)

df["Цена_за_ед"] = df["ТО, руб"] / df["ТО, в е.изм."]

# Берём товары с известной фасовкой, цена по годам — медианная
check = (
    df.dropna(subset=["Объём_г"])
    .groupby(["Номенклатура", "Объём_г"])
    .agg(цена_за_ед=("Цена_за_ед", "median"), записей=("Цена_за_ед", "size"))
    .reset_index()
)
check = check[check["записей"] > 100]
# Покажем по 2 примера на фасовку с их ценами
print("Фасовка → медианная цена за единицу (примеры):")
for vol in sorted(check["Объём_г"].unique()):
    sub = check[check["Объём_г"] == vol].head(2)
    for _, r in sub.iterrows():
        print(f"  {vol:>6} г → {r['цена_за_ед']:>7.2f} руб/ед   ({r['Номенклатура'][:60]}...)")

# ---------------------------------------------------------------
# 5. Активность товаров: кто продавался в начале периода, кто сейчас
#    Сравниваем ТОЛЬКО одинаковые периоды: январь-июль 2022 vs январь-июль 2026
# ---------------------------------------------------------------
print("\n" + "=" * 70)
print("5. УШЕДШИЕ И ПРИШЕДШИЕ ТОВАРЫ (янв-июль 2022 vs янв-июль 2026)")
print("=" * 70)

def half_year(y: int) -> set:
    """Набор кодов, продававшихся в январе-июле года y."""
    m = df[(df["Год"] == y) & (df["День"].dt.month <= 7)]
    return set(m["Код номенклатуры"])

set_2022 = half_year(2022)
set_2026 = half_year(2026)

gone = set_2022 - set_2026          # были в 2022, исчезли к 2026
arrived = set_2026 - set_2022       # появились к 2026
stayed = set_2022 & set_2026        # были и остались

print(f"Товаров в янв-июле 2022: {len(set_2022)}")
print(f"Товаров в янв-июле 2026: {len(set_2026)}")
print(f"Исчезли к 2026: {len(gone)}")
print(f"Появились к 2026: {len(arrived)}")
print(f"Остались в обеих периодах: {len(stayed)}")

names = df.groupby("Код номенклатуры")["Номенклатура"].first()
print("\nИсчезнувшие (последняя известная запись):")
for code in sorted(gone):
    last = df[df["Код номенклатуры"] == code]["День"].max().date()
    print(f"  {code}: до {last} — {names[code]}")
print("\nПоявившиеся (первая запись):")
for code in sorted(arrived):
    first = df[df["Код номенклатуры"] == code]["День"].min().date()
    print(f"  {code}: с {first} — {names[code]}")

print("\n" + "=" * 70)
print("Аудит завершён.")
print("=" * 70)
