# -*- coding: utf-8 -*-
"""
10_abc_analysis.py — ABC-анализ ассортимента (правило 20/80)
=============================================================
Группы по кумулятивной доле выручки:
  A — первые 80% (звёзды, кормят магазин),
  B — следующие 15% (середняки),
  C — последние 5% (аутсайдеры, кандидаты на пересмотр).

Период: последние 12 ПОЛНЫХ месяцев (2025-08-01 … 2026-07-31).
Расчёт по «историям» товара (правило пользователя: шринкфляция —
продолжение того же товара; пары из output/пары_шринкфляции.xlsx).

Дополнительно: ABC по штукам + сравнение с 2022 годом (кто был
звездой тогда и где он сейчас).

Выход: output/ABC_анализ.xlsx + печать в консоль.
"""

import pandas as pd

# ---------------------------------------------------------------
# Чтение и склейка в истории (как в 07)
# ---------------------------------------------------------------
df = pd.read_excel(
    "data/Молоко.xlsx",
    dtype={"Код номенклатуры": str},
    parse_dates=["День"],
)
pairs = pd.read_excel("output/пары_шринкфляции.xlsx", dtype=str)

chain_map = {}
for _, p in pairs.iterrows():
    chain_map[p["Код старой упаковки"]] = p["Код старой упаковки"]
    chain_map[p["Код новой упаковки"]] = p["Код старой упаковки"]
for code in df["Код номенклатуры"].unique():
    chain_map.setdefault(code, code)

df["История"] = df["Код номенклатуры"].map(chain_map)

chain_names = {}
for _, p in pairs.iterrows():
    chain_names[p["Код старой упаковки"]] = (
        f"{p['Название старой упаковки'][:38]} → {p['Название новой упаковки'][:38]}"
    )
first_name = df.groupby("Код номенклатуры")["Номенклатура"].first().to_dict()


def history_label(h: str) -> str:
    return chain_names.get(h, first_name[h])


# ---------------------------------------------------------------
# ABC-функция
# ---------------------------------------------------------------
def abc_groups(s: pd.Series) -> pd.Series:
    """Возвращает группу A/B/C по кумулятивной доле (80/15/5)."""
    cum = s.sort_values(ascending=False).cumsum() / s.sum()
    out = pd.Series("C", index=s.index)
    out[cum <= 0.80] = "A"
    out[(cum > 0.80) & (cum <= 0.95)] = "B"
    return out


def abc_table(data: pd.DataFrame, value_col: str) -> pd.DataFrame:
    """Сводная таблица ABC по историям."""
    g = data.groupby("История")[value_col].sum().sort_values(ascending=False)
    g = g[g > 0]
    cum = g.cumsum() / g.sum()
    groups = abc_groups(g)
    tbl = pd.DataFrame(
        {
            "История": g.index,
            "Название": [history_label(h) for h in g.index],
            "Значение": g.values,
            "Доля": g.values / g.sum(),
            "Кумулятивная_доля": cum.values,
            "Группа": groups.values,
        }
    )
    return tbl


# ---------------------------------------------------------------
# Периоды
# ---------------------------------------------------------------
recent = df[(df["День"] >= "2025-08-01") & (df["День"] <= "2026-07-31")]
h1_2022 = df[(df["День"].dt.year == 2022) & (df["День"].dt.month <= 7)]

print("=" * 78)
print("ABC-АНАЛИЗ ПО ВЫРУЧКЕ (последние 12 полных мес: 08.2025–07.2026)")
print("=" * 78)

abc_rub = abc_table(recent, "ТО, руб")
for grp in ["A", "B", "C"]:
    sub = abc_rub[abc_rub["Группа"] == grp]
    print(f"\nГруппа {grp}: {len(sub)} историй, выручка {sub['Значение'].sum():,.0f} руб "
          f"({sub['Значение'].sum() / abc_rub['Значение'].sum():.1%} от всего)".replace(",", " "))
    if grp == "A":
        for _, r in sub.iterrows():
            print(f"   {r['Значение']:>10,.0f} руб ({r['Доля']:5.1%})  {r['Название'][:65]}".replace(",", " "))

# ---------------------------------------------------------------
# ABC по штукам
# ---------------------------------------------------------------
print("\n" + "=" * 78)
print("ABC-АНАЛИЗ ПО ШТУКАМ (тот же период)")
print("=" * 78)

abc_qty = abc_table(recent, "ТО, в е.изм.")
for grp in ["A", "B", "C"]:
    sub = abc_qty[abc_qty["Группа"] == grp]
    print(f"Группа {grp}: {len(sub)} историй, штук {sub['Значение'].sum():,.0f} "
          f"({sub['Значение'].sum() / abc_qty['Значение'].sum():.1%})".replace(",", " "))

# ---------------------------------------------------------------
# Сравнение с 2022: кто был звездой и где он сейчас
# ---------------------------------------------------------------
print("\n" + "=" * 78)
print("СРАВНЕНИЕ С 2022: ГРУППЫ ТОГДА И СЕЙЧАС (по выручке)")
print("=" * 78)

abc_2022 = abc_table(h1_2022, "ТО, руб")
compare = pd.DataFrame(
    {
        "Группа_2022": abc_2022.set_index("История")["Группа"],
        "Группа_сейчас": abc_rub.set_index("История")["Группа"],
    }
)
compare = compare.fillna("—")

print("\nИстории, которые были в группе A в 2022:")
for h, row in compare[compare["Группа_2022"] == "A"].iterrows():
    cur = row["Группа_сейчас"]
    flag = ""
    if cur == "—":
        flag = "  ← УШЛА ИЗ ПРОДАЖ"
    elif cur != "A":
        flag = f"  ← деградировала в {cur}"
    print(f"  {history_label(h)[:60]:<62} 2022: A → сейчас: {cur}{flag}")

print("\nИстории, которые стали звездами (A) сейчас, но не были в 2022:")
for h, row in compare[compare["Группа_сейчас"] == "A"].iterrows():
    if row["Группа_2022"] != "A":
        print(f"  {history_label(h)[:60]:<62} 2022: {row['Группа_2022']} → сейчас: A")

# ---------------------------------------------------------------
# Сохранение книги
# ---------------------------------------------------------------
# Полная таблица: выручка + штуки + группы + доля
full = abc_rub.merge(
    abc_qty[["История", "Значение", "Группа"]].rename(
        columns={"Значение": "Штук", "Группа": "Группа_по_штукам"}
    ),
    on="История",
    how="left",
)
full["Название"] = full["История"].map(history_label)
full["Статус_сейчас"] = full["История"].map(
    lambda h: compare.loc[h, "Группа_сейчас"] if h in compare.index else "—"
)
full = full.sort_values("Значение", ascending=False)

compare_reset = compare.reset_index()
compare_reset["Название"] = compare_reset["История"].map(history_label)

# Понятные заголовки колонок: сущность + единица измерения
R_RUB = {
    "История": "Код истории",
    "Название": "Название товара (история)",
    "Значение": "Выручка за 12 мес, руб",
    "Доля": "Доля выручки, %",
    "Кумулятивная_доля": "Накопленная доля, %",
    "Группа": "Группа ABC",
    "Штук": "Продано за 12 мес, штук",
    "Группа_по_штукам": "Группа по штукам",
    "Статус_сейчас": "Группа сейчас (сравнение с 2022)",
}
R_QTY = {
    "История": "Код истории",
    "Название": "Название товара (история)",
    "Значение": "Продано за 12 мес, штук",
    "Доля": "Доля штук, %",
    "Кумулятивная_доля": "Накопленная доля, %",
    "Группа": "Группа ABC",
}
R_CMP = {
    "История": "Код истории",
    "Название": "Название товара (история)",
    "Группа_2022": "Группа в 2022 (янв–июл)",
    "Группа_сейчас": "Группа сейчас (авг 2025 – июл 2026)",
}

OUT = "output/ABC_анализ.xlsx"
with pd.ExcelWriter(OUT, engine="openpyxl") as writer:
    full.rename(columns=R_RUB).to_excel(writer, sheet_name="ABC_по_выручке", index=False)
    abc_qty.rename(columns=R_QTY).to_excel(writer, sheet_name="ABC_по_штукам", index=False)
    compare_reset.rename(columns=R_CMP).to_excel(writer, sheet_name="Сравнение_с_2022", index=False)

print(f"\nСохранено: {OUT}")
print("  Лист «ABC_по_выручке»:", len(full), "историй")
print("  Лист «ABC_по_штукам»:", len(abc_qty), "историй")
print("  Лист «Сравнение_с_2022»:", len(compare_reset), "историй")
