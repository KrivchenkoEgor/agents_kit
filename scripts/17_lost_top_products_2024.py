# -*- coding: utf-8 -*-
"""
17_lost_top_products_2024.py — Потерянные топ-товары 2024 (нет в продажах 2026)
==========================================================================
Задача пользователя: в каждой группе показать позиции, которые в 2024 году
входили в топ по продажам (объём, кг) И по выручке (руб), но которых нет
в продажах 2026 года.

Близнец скрипта 16 (база 2023): та же логика:
  1) 2024: по каждой группе ранжируем товары по объёму (кг) и выручке (руб);
  2) топ = первые 10; «звёзды» = пересечение двух топов;
  3) потерянные = звёзды без продаж в 2026 (по коду);
  4) проверка «продолжений» по правилу пользователя про шринкфляцию:
     тот же товар, сменивший фасовку/код (одинаковое ядро названия,
     первая продажа продолжения рядом с последней продажей старого).
     Мягкий проход — бренд + отличительное слово в той же группе
     (ловит маркетинговые приставки вроде «Как тогда», зазор −480..730).

Выход: output/Отчет_потерянные_топы_2024_2026.xlsx
"""

import re
import numpy as np
import pandas as pd

# ---------------------------------------------------------------
# Чтение
# ---------------------------------------------------------------
df = pd.read_excel(
    "data/колбасаНФ.xlsx",
    dtype={"Код ": str},
    parse_dates=["День"],
)
df = df.rename(columns={"Код ": "Код"})

s = df[(df["ТО, в е.изм."] > 0) & (df["ТО, руб"] > 0)].copy()
y24 = s[s["День"].dt.year == 2024]
y26 = s[s["День"].dt.year == 2026]

# ---------------------------------------------------------------
# Ядро названия: без фасовки и маркеров упаковки (в/у, п/к и т.п.)
# ---------------------------------------------------------------
def parse_weight(name):
    m = re.search(r"(\d+(?:[.,]\d+)?)\s*(г|кг)\b", name)
    if not m:
        return None
    v = float(m.group(1).replace(",", "."))
    return v * 1000 if m.group(2) == "кг" else v

def core_name(name):
    name = re.sub(r"\d+(?:[.,]\d+)?\s*(г|кг)\b", "", name)
    name = re.sub(r"\s*(?:в/у|в/с|в/к|п/к|с/у|бзмж)\b", " ", name)
    name = re.sub(r"\s+", " ", name).strip()
    return name

# ---------------------------------------------------------------
# Сводки по товарам за 2024
# ---------------------------------------------------------------
agg24 = (
    y24.groupby(["группа", "Код", "Номенклатура"])
    .agg(
        Объём_2024_кг=("ТО, в е.изм.", "sum"),
        Выручка_2024_руб=("ТО, руб", "sum"),
        Дней_продаж_2024=("День", "nunique"),
    )
    .reset_index()
)

TOP_N = 10
agg24["Ранг_по_объёму"] = agg24.groupby("группа")["Объём_2024_кг"].rank(
    method="min", ascending=False
).astype(int)
agg24["Ранг_по_выручке"] = agg24.groupby("группа")["Выручка_2024_руб"].rank(
    method="min", ascending=False
).astype(int)

top_vol = agg24[agg24["Ранг_по_объёму"] <= TOP_N]
top_rev = agg24[agg24["Ранг_по_выручке"] <= TOP_N]

# «Звёзды» 2024: топ и по объёму, и по выручке
stars = top_vol.merge(top_rev[["группа", "Код"]], on=["группа", "Код"], how="inner")

# Кто продавался в 2026
codes26 = set(y26["Код"].unique())
stars["Продано_2026_кг"] = stars["Код"].map(
    y26.groupby("Код")["ТО, в е.изм."].sum()
).fillna(0.0)

# Потерянные по коду: в 2026 нет продаж
lost = stars[stars["Продано_2026_кг"] == 0].copy()

last_sale = s.groupby("Код")["День"].max()
# Первая продажа кода — за ВЕСЬ период (продолжение могло стартовать ещё в 2024)
first_sale_all = s.groupby("Код")["День"].min()
first_name = s.groupby("Код")["Номенклатура"].first()

lost["Последняя продажа"] = lost["Код"].map(last_sale).dt.date

# Справочник «живых» 2026: код → (ядро, вес, первая продажа за весь период, группа)
alive = {}
g26 = y26.groupby("Код")["группа"].first()
for code in codes26:
    nm = first_name[code]
    alive[code] = {
        "ядро": core_name(nm),
        "вес": parse_weight(nm),
        "первая_продажа": first_sale_all[code],
        "название": nm,
        "группа": g26[code],
    }

# Общие слова (тип продукта) — не считаем их «отличительными»
STOP_WORDS = {
    "молочная", "молочные", "вареная", "варенокопченая", "сырокопченая",
    "полукопченая", "копченая", "колбаса", "ветчина", "сосиски",
    "шпикачки", "сардельки", "сервелат", "вареный",
}
BRAND_RE = re.compile(r"[А-ЯЁ]{2,}(?:\s+[А-ЯЁ]{2,})*")

# ---------------------------------------------------------------
# Поиск продолжений по правилу пользователя (шринкфляция)
# ---------------------------------------------------------------
def find_pairs(r):
    """Ищем в 2026 позиции с тем же ядром названия и разумным зазором."""
    core = core_name(r["Номенклатура"])
    old_w = parse_weight(r["Номенклатура"])
    last_d = last_sale[r["Код"]]
    cands = []
    for code, info in alive.items():
        if info["ядро"] != core:
            continue
        gap = (info["первая_продажа"] - last_d).days
        # −60: старая и новая фасовка могли продаваться параллельно (остатки);
        # +730: продолжение могло вернуться после долгого перерыва
        if gap < -60 or gap > 730:
            continue
        cands.append((gap, code, info))
    if not cands:
        return None, None, None, None, "ядро"
    cands.sort(key=lambda x: x[0])
    gap, code, info = cands[0]
    return code, info, gap, old_w, "ядро"


def find_pairs_lenient(r):
    """Мягкий поиск: тот же бренд и отличительное слово в той же группе.

    Ловит переименования с маркетинговой приставкой, когда ядро названия
    не совпало (пример: «… Министерский в/к 320г» → «… Как тогда
    Министерский в/к 270г»).
    """
    name = r["Номенклатура"]
    old_w = parse_weight(name)
    last_d = last_sale[r["Код"]]
    m = BRAND_RE.search(name)
    brand = m.group(0) if m else ""
    # сравнение по нижнему регистру: «ОМСКИЙ».lower() == «омский»,
    # иначе слова бренда остаются в «отличительных» и ловятся ложные пары
    brand_tokens = {t.lower() for t in brand.split()}
    sig = [
        w for w in re.findall(r"[А-Яа-яЁё]{6,}", name)
        if w.lower() not in brand_tokens and w.lower() not in STOP_WORDS
    ]
    cands = []
    for code, info in alive.items():
        if info["группа"] != r["группа"]:
            continue
        if brand and brand not in info["название"]:
            continue
        if not any(w in info["название"] for w in sig):
            continue
        gap = (info["первая_продажа"] - last_d).days
        # мягкий поиск допускает долгое параллельное существование размеров
        if gap < -480 or gap > 730:
            continue
        cands.append((gap, code, info))
    if not cands:
        return None, None, None, None, "мягкий"
    cands.sort(key=lambda x: x[0])
    gap, code, info = cands[0]
    return code, info, gap, old_w, "мягкий"

status_rows = []
for _, r in lost.iterrows():
    old_w = parse_weight(r["Номенклатура"])
    r["Старая_фасовка_г"] = old_w
    code_new, info, gap, _, method = find_pairs(r)
    if info is None:
        code_new, info, gap, _, method = find_pairs_lenient(r)
    if info is None:
        r["Статус"] = "исчез"
        r["Продолжение"] = ""
        r["Как найден"] = ""
    else:
        new_w = info["вес"]
        if old_w is not None and new_w is not None and new_w < old_w and (gap <= 180 or gap < 0):
            r["Статус"] = "шринкфляция (продолжение)"
        elif old_w is not None and new_w is not None and new_w < old_w:
            r["Статус"] = f"продолжение, но зазор {gap} дн"
        elif old_w is not None and new_w is not None and new_w == old_w:
            r["Статус"] = "перекодировка (продолжение)"
        elif old_w is not None and new_w is not None and new_w > old_w:
            r["Статус"] = "продолжение? (фасовка БОЛЬШЕ)"
        else:
            r["Статус"] = "продолжение? (вес не определён)"
        r["Продолжение"] = f"{code_new} «{info['название'][:50]}»"
        r["Первая_продажа_продолжения"] = info["первая_продажа"].date()
        r["Зазор_дней"] = gap
        r["Новая_фасовка_г"] = new_w
        r["Как найден"] = "ядро названия" if method == "ядро" else "бренд + тип (мягкий)"
    status_rows.append(r)

lost = pd.DataFrame(status_rows)

# ---------------------------------------------------------------
# Итоговая таблица
# ---------------------------------------------------------------
out = lost.sort_values(["группа", "Ранг_по_объёму"]).reset_index(drop=True)
out = out.rename(
    columns={
        "группа": "Группа",
        "Номенклатура": "Название товара",
        "Ранг_по_объёму": "Место по продажам в 2024 (объём)",
        "Объём_2024_кг": "Продано в 2024, кг",
        "Ранг_по_выручке": "Место по выручке в 2024",
        "Выручка_2024_руб": "Выручка в 2024, руб",
        "Дней_продаж_2024": "Дней с продажами в 2024",
        "Последняя продажа": "Последняя дата продажи",
        "Продолжение": "Продолжение в 2026 (код и название)",
        "Первая_продажа_продолжения": "Первая продажа продолжения",
        "Зазор_дней": "Зазор, дней",
        "Старая_фасовка_г": "Фасовка старая, г",
        "Новая_фасовка_г": "Фасовка новая, г",
        "Как найден": "Как найдено продолжение",
    }
)
out["Выручка в 2024, руб"] = out["Выручка в 2024, руб"].round(2)
out["Продано в 2024, кг"] = out["Продано в 2024, кг"].round(1)
# у «исчез» строк колонки продолжения пустые — ставим «—» вместо пустоты
out = out.drop(columns=["Продано_2026_кг"])
for col in ["Продолжение в 2026 (код и название)", "Первая продажа продолжения",
            "Зазор, дней", "Фасовка новая, г", "Как найдено продолжение"]:
    out[col] = out[col].replace({"": "—"}).fillna("—")

# Справочные листы: полные топы 2024
for name, rank_col, val_col, val_name in [
    ("Топ-10_по_объёму_2024", "Ранг_по_объёму", "Объём_2024_кг", "Продано в 2024, кг"),
    ("Топ-10_по_выручке_2024", "Ранг_по_выручке", "Выручка_2024_руб", "Выручка в 2024, руб"),
]:
    t = (top_vol if name.startswith("Топ-10_по_объёму") else top_rev).sort_values(["группа", rank_col]).copy()
    t["В продаже 2026"] = np.where(t["Код"].isin(codes26), "да", "НЕТ")
    t = t.rename(columns={"группа": "Группа", "Номенклатура": "Название товара", val_col: val_name})
    t = t[["Группа", "Код", "Название товара", val_name, "В продаже 2026"]]
    if name.startswith("Топ-10_по_объёму"):
        top_vol_tbl = t
    else:
        top_rev_tbl = t

# ---------------------------------------------------------------
# Печать
# ---------------------------------------------------------------
print("=" * 78)
print("ТОП-ТОВАРЫ 2024, КОТОРЫХ НЕТ В ПРОДАЖАХ 2026 (по коду) — по группам")
print("=" * 78)
for g, grp in out.groupby("Группа"):
    print(f"\n— {g}:")
    for _, r in grp.iterrows():
        tail = f"→ {r['Продолжение в 2026 (код и название)']}" if r["Статус"] != "исчез" else ""
        print(f"  [{r['Статус'][:14]:<14}] {r['Название товара'][:48]} {tail}")

print("\nИтого:", len(out), "«звёзд» 2024 без продаж 2026 по коду:")
print(out["Статус"].value_counts().to_string())

# ---------------------------------------------------------------
# Сохранение
# ---------------------------------------------------------------
OUT = "output/Отчет_потерянные_топы_2024_2026.xlsx"
with pd.ExcelWriter(OUT, engine="openpyxl") as writer:
    out.to_excel(writer, sheet_name="Потерянные_топы", index=False)
    top_vol_tbl.to_excel(writer, sheet_name="Топ-10_по_объёму_2024", index=False)
    top_rev_tbl.to_excel(writer, sheet_name="Топ-10_по_выручке_2024", index=False)

print(f"\nСохранено: {OUT}")
print("  Лист «Потерянные_топы»:", len(out), "строк (со статусом и продолжением)")
print("  Лист «Топ-10_по_объёму_2024»:", len(top_vol_tbl), "строк")
print("  Лист «Топ-10_по_выручке_2024»:", len(top_rev_tbl), "строк")