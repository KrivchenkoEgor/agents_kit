# -*- coding: utf-8 -*-
"""
06_build_chains.py — Построение «историй товаров» с учётом шринкфляции
======================================================================
Правило пользователя: товар, подвергшийся шринкфляции (сменил фасовку
на меньшую, но продолжил продаваться), считается ПРОДОЛЖЕНИЕМ продаж
того же товара. Такие пары склеиваются в одну «историю».

Критерии склейки (пара ушедший → пришедший):
  1) тот же бренд (капс-группа из названия);
  2) зазор между последней продажей старого и первой продажей нового
     от −30 до +90 дней (лёгкое перекрытие допустимо — продажа остатков);
  3) фасовка нового меньше фасовки старого (шринкфляция);
  4) жирность совпадает (у обоих извлекается) — чтобы не склеить 2.5% с 3.2%.

Спорные пары (фасовка уменьшена, но жирность не совпадает) выводятся
отдельным списком — решение по ним принимает пользователь.

Вход:  data/Молоко.xlsx
Выход: output/пары_шринкфляции.xlsx + печать в консоль
"""

import re
from typing import Optional

import pandas as pd

# ---------------------------------------------------------------
# Чтение и признаки
# ---------------------------------------------------------------
df = pd.read_excel(
    "data/Молоко.xlsx",
    dtype={"Код номенклатуры": str},
    parse_dates=["День"],
)

VOL_PATTERN = re.compile(r"(\d+(?:[.,]\d+)?)\s*(г|мл|л|кг)", re.IGNORECASE)
FAT_PATTERN = re.compile(r"(\d+(?:[.,]\d+)?)\s*%")
# Бренд — первая группа КАПС-слов (минимум 2 капс-буквы подряд),
# например «ДОМИК В ДЕРЕВНЕ», «ЗЕЛЕНЫЙ ЛУГ». Слово «Молоко» не матчится,
# потому что после «М» идут строчные буквы.
BRAND_PATTERN = re.compile(r"[А-ЯЁ]{2,}[0-9.]*(?:\s+[А-ЯЁ]{2,}[0-9.]*)*")


def parse_volume(name: str) -> Optional[float]:
    m = VOL_PATTERN.search(name)
    if not m:
        return None
    val = float(m.group(1).replace(",", "."))
    unit = m.group(2).lower()
    if unit == "мл":
        return val
    if unit == "л":
        return val * 1000
    if unit == "г":
        return val
    if unit == "кг":
        return val * 1000
    return None


def parse_fat(name: str) -> Optional[float]:
    m = FAT_PATTERN.search(name)
    return float(m.group(1).replace(",", ".")) if m else None


def brand_of(name: str) -> str:
    m = BRAND_PATTERN.search(name)
    return m.group(0).strip() if m else name.split()[0]


df["Фасовка_г"] = df["Номенклатура"].map(parse_volume)
df["Жирность"] = df["Номенклатура"].map(parse_fat)
df["Бренд"] = df["Номенклатура"].map(brand_of)

# ---------------------------------------------------------------
# Сводка по каждому товару
# ---------------------------------------------------------------
info = (
    df.groupby("Код номенклатуры")
    .agg(
        Бренд=("Бренд", "first"),
        Название=("Номенклатура", "first"),
        Жирность=("Жирность", "first"),
        Фасовка_г=("Фасовка_г", "first"),
        Первая=("День", "min"),
        Последняя=("День", "max"),
    )
    .reset_index()
)

# «Ушедшие»: не было в янв-июле 2026 и последняя продажа до 2026-01-01
active_2026h1 = set(df[(df["Год_"] == 2026) & (df["День"].dt.month <= 7)]["Код номенклатуры"]) if False else set(
    df[(df["День"].dt.year == 2026) & (df["День"].dt.month <= 7)]["Код номенклатуры"]
)
gone = info[~info["Код номенклатуры"].isin(active_2026h1)].copy()
gone = gone[gone["Последняя"] < pd.Timestamp("2026-01-01")]

# «Пришедшие»: не было в янв-июле 2022
active_2022h1 = set(
    df[(df["День"].dt.year == 2022) & (df["День"].dt.month <= 7)]["Код номенклатуры"]
)
arrived = info[~info["Код номенклатуры"].isin(active_2022h1)].copy()

# ---------------------------------------------------------------
# Поиск пар
# ---------------------------------------------------------------
candidates = []   # (gap, ушедший, пришедший, жирность совпала)
for _, g in gone.iterrows():
    for _, a in arrived.iterrows():
        if g["Бренд"] != a["Бренд"]:
            continue
        if not (g["Фасовка_г"] and a["Фасовка_г"]):
            continue
        if a["Фасовка_г"] >= g["Фасовка_г"]:
            continue  # нужна именно шринкфляция: фасовка уменьшилась
        gap = (a["Первая"] - g["Последняя"]).days
        if not (-30 <= gap <= 90):
            continue
        fat_ok = (
            g["Жирность"] is not None
            and a["Жирность"] is not None
            and abs(g["Жирность"] - a["Жирность"]) < 0.1
        )
        candidates.append(
            {"gap": gap, "g": g, "a": a, "fat_ok": fat_ok}
        )

# Жадное сопоставление: сначала пары с совпадением жирности и малым зазором
candidates.sort(key=lambda c: (not c["fat_ok"], abs(c["gap"])))
used_g, used_a = set(), set()
pairs = []
for c in candidates:
    if c["g"]["Код номенклатуры"] in used_g or c["a"]["Код номенклатуры"] in used_a:
        continue
    if not c["fat_ok"]:
        continue  # в основные пары — только с совпавшей жирностью
    pairs.append(c)
    used_g.add(c["g"]["Код номенклатуры"])
    used_a.add(c["a"]["Код номенклатуры"])

# Спорные: фасовка уменьшена, зазор в норме, но жирность не совпала
# (и участники ещё не заняты в основных парах)
contested = [
    c for c in candidates
    if not c["fat_ok"]
    and c["g"]["Код номенклатуры"] not in used_g
    and c["a"]["Код номенклатуры"] not in used_a
]

# ---------------------------------------------------------------
# Вывод
# ---------------------------------------------------------------
print("=" * 70)
print("СКЛЕЕННЫЕ ПАРЫ (шринкфляция: бренд + жирность совпали)")
print("=" * 70)
print(f"Пар: {len(pairs)}\n")
for c in sorted(pairs, key=lambda c: c["gap"]):
    g, a = c["g"], c["a"]
    print(f"  {g['Последняя'].date()} {g['Фасовка_г']:.0f}г → {a['Первая'].date()} {a['Фасовка_г']:.0f}г  (зазор {c['gap']} дн)")
    print(f"    {g['Код номенклатуры']} {g['Название'][:60]}")
    print(f"    {a['Код номенклатуры']} {a['Название'][:60]}")

print("\n" + "=" * 70)
print("СПОРНЫЕ ПАРЫ (фасовка уменьшена, жирность НЕ совпала)")
print("=" * 70)
print(f"Пар: {len(contested)}\n")
for c in sorted(contested, key=lambda c: c["gap"])[:20]:
    g, a = c["g"], c["a"]
    print(f"  {g['Последняя'].date()} {g['Фасовка_г']:.0f}г ({g['Жирность']}%) → "
          f"{a['Первая'].date()} {a['Фасовка_г']:.0f}г ({a['Жирность']}%)  (зазор {c['gap']} дн)")
    print(f"    {g['Название'][:55]}")
    print(f"    {a['Название'][:55]}")

# ---------------------------------------------------------------
# Сохранение
# ---------------------------------------------------------------
pair_rows = []
for c in sorted(pairs, key=lambda c: c["gap"]):
    g, a = c["g"], c["a"]
    pair_rows.append(
        {
            "Код старой упаковки": g["Код номенклатуры"],
            "Код новой упаковки": a["Код номенклатуры"],
            "Название старой упаковки": g["Название"],
            "Название новой упаковки": a["Название"],
            "Фасовка старая, г/мл": g["Фасовка_г"],
            "Фасовка новая, г/мл": a["Фасовка_г"],
            "Последняя продажа старой упаковки": g["Последняя"].date(),
            "Первая продажа новой упаковки": a["Первая"].date(),
            "Зазор, дней": c["gap"],
            "Жирность старая, %": g["Жирность"],
            "Жирность новая, %": a["Жирность"],
        }
    )
out = pd.DataFrame(pair_rows)
OUT = "output/пары_шринкфляции.xlsx"
with pd.ExcelWriter(OUT, engine="openpyxl") as writer:
    out.to_excel(writer, sheet_name="Пары_шринкфляции", index=False)
print(f"\nСохранено: {OUT} ({len(out)} пар)")
