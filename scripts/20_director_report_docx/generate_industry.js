// Абзац основного текста: по ширине, отступ первой строки
function body(text, opts = {}) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    indent: { firstLine: 480 },
    spacing: { after: opts.after !== undefined ? opts.after : 100 },
    keepNext: opts.keepNext || false,
    children: [new TextRun({ text, size: 24 })],
  });
}

// Абзац с жирным вступлением («Вывод: ...» и т.п.)
function bodyLead(lead, text) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    indent: { firstLine: 480 },
    spacing: { after: 140 },
    children: [
      new TextRun({ text: lead + " ", bold: true, size: 24 }),
      new TextRun({ text, size: 24 }),
    ],
  });
}

// Заголовок раздела (H1)
function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    keepNext: true,
    spacing: { before: 200, after: 80 },
    children: [new TextRun({ text, bold: true, size: 28, color: "000000" })],
  });
}

// Подзаголовок (H2)
function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    keepNext: true,
    spacing: { before: 160, after: 60 },
    children: [new TextRun({ text, bold: true, size: 26, color: "000000" })],
  });
}

// Мелкая серая приписка (примечание, дисклеймер)
function note(text) {
  return new Paragraph({
    spacing: { after: 100 },
    children: [new TextRun({ text, size: 18, color: "606060", italics: true })],
  });
}

// Пункт рекомендации (нумерованный список)
function recItem(text) {
  return new Paragraph({
    numbering: { reference: "recom", level: 0 },
    spacing: { after: 60 },
    children: [new TextRun({ text, size: 24 })],
  });
}

// Строка источника (нумерованный список, мелкий шрифт)
function srcItem(text, url) {
  return new Paragraph({
    numbering: { reference: "src", level: 0 },
    spacing: { after: 30 },
    children: [
      new TextRun({ text, size: 18, color: "404040" }),
      new TextRun({ text: "  " + url, size: 16, color: "808080" }),
    ],
  });
}

// Таблица: шапка с заливкой, горизонтальные линии
function makeTable(headers, rows, widths, opts = {}) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 2, color: "9AA6B2" },
      bottom: { style: BorderStyle.SINGLE, size: 2, color: "9AA6B2" },
      left: { style: BorderStyle.NONE },
      right: { style: BorderStyle.NONE },
      insideHorizontal: { style: BorderStyle.SINGLE, size: 1, color: "D0D0D0" },
      insideVertical: { style: BorderStyle.NONE },
    },
    rows: [
      new TableRow({
        tableHeader: true,
        cantSplit: true,
        children: headers.map((h, i) => new TableCell({
          width: { size: widths[i], type: WidthType.PERCENTAGE },
          shading: { type: ShadingType.CLEAR, fill: "529286" },
          margins: { top: 40, bottom: 40, left: 80, right: 80 },
          children: [new Paragraph({ children: [new TextRun({ text: h, bold: true, size: 18, color: "FFFFFF" })] })],
        })),
      }),
      ...rows.map((r) => new TableRow({
        cantSplit: true,
        children: r.map((c, i) => new TableCell({
          width: { size: widths[i], type: WidthType.PERCENTAGE },
          margins: { top: 40, bottom: 40, left: 80, right: 80 },
          children: [new Paragraph({
            children: [new TextRun({ text: c, size: (opts.fontSize || 18) })],
          })],
        })),
      })),
    ],
  });
}

