// Абзац основного текста: выравнивание по ширине, отступ первой строки
function body(text, opts = {}) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    indent: { firstLine: 480 },
    spacing: { after: opts.after !== undefined ? opts.after : 80 },
    keepNext: opts.keepNext || false,
    children: [new TextRun({ text, size: 24 })],
  });
}

// Заголовок раздела (H1, чтобы Word видел структуру документа)
function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 140, after: 60 },
    children: [new TextRun({ text, bold: true, size: 28, color: "000000" })],
  });
}

// Пункт рекомендации (нумерованный список)
function recItem(text) {
  return new Paragraph({
    numbering: { reference: "recom", level: 0 },
    spacing: { after: 50 },
    children: [new TextRun({ text, size: 24 })],
  });
}

// Таблица в стиле «горизонтальные линии»: шапка с заливкой, тонкие разделители
function makeTable(headers, rows, widths) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 2, color: "9AA6B2" },
      bottom: { style: BorderStyle.SINGLE, size: 2, color: "9AA6B2" },
      left: { style: BorderStyle.NONE },
      right: { style: BorderStyle.NONE },
      insideHorizontal: { style: BorderStyle.SINGLE, size: 1, color: "D0D0D0" },
      insideVertical: { style: BorderStyle.NONE },
    },
    rows: [
      new TableRow({
        tableHeader: true,          // шапка повторяется при переносе таблицы
        cantSplit: true,
        children: headers.map((h, i) => new TableCell({
          width: { size: widths[i], type: WidthType.PERCENTAGE },
          shading: { type: ShadingType.CLEAR, fill: "529286" },
          margins: { top: 40, bottom: 40, left: 80, right: 80 },
          children: [new Paragraph({ children: [new TextRun({ text: h, bold: true, size: 18, color: "FFFFFF" })] })],
        })),
      }),
      ...rows.map((r) => new TableRow({
        cantSplit: true,
        children: r.map((c, i) => new TableCell({
          width: { size: widths[i], type: WidthType.PERCENTAGE },
          margins: { top: 40, bottom: 40, left: 80, right: 80 },
          children: [new Paragraph({ children: [new TextRun({ text: c, size: 18 })] })],
        })),
      })),
    ],
  });
}

