# Сверка двух файлов на соответствие заданию:
#   «Покажи в каждой группе позиции, которые в 2023г входили в топ-товары
#    по штукам и рублям и которых нет в продажах 2026г, создай эксель файл отчёта»
# Сравниваются:
#   A) output/Отчет_потерянные_топы_2023_2026.xlsx   (наш отчёт, задача 16)
#   B) data/20260812_115818.xlsx                     (файл от пользователя/другого инструмента)
# Истина берётся из data/колбасаНФ.xlsx (246 286 строк).
# Результат: output/Сравнение_файлов_потерянных_топов.xlsx
# =====================================================================
import pandas as pd

SRC = "data/колбасаНФ.xlsx"
FILE_A = "output/Отчет_потерянные_топы_2023_2026.xlsx"
FILE_B = "data/20260812_115818.xlsx"
OUT = "output/Сравнение_файлов_потерянных_топов.xlsx"

# ---------- 1. Истина из исходника ----------
df = pd.read_excel(SRC, dtype={"Код ": str})
df["День"] = pd.to_datetime(df["День"])
df["Код "] = df["Код "].str.strip().str.zfill(5)          # нормализация ведущих нулей
df["тип"] = df.groupby("Код ")["ТО, в е.изм."].transform(
    lambda s: "весовой" if ((s % 1) != 0).any() else "штучный")
y23 = df[df["День"].dt.year == 2023]
y26_codes = set(df[df["День"].dt.year == 2026]["Код "])
names = df.groupby("Код ")["Номенклатура"].first()

rows = []
for g in df["группа"].unique():
    p = y23[y23["группа"] == g].groupby("Код ")
    a = p["ТО, в е.изм."].sum(); r = p["ТО, руб"].sum()
    ri = a.rank(ascending=False, method="min").astype(int)
    rr = r.rank(ascending=False, method="min").astype(int)
    cand = (ri <= 10) & (rr <= 10)                        # критерий: оба топа
    for c in a.index[cand]:
        rows.append({"группа": g, "код": c, "название": names[c],
                     "тип": "весовой (кг)" if df.loc[df["Код "]==c, "тип"].iloc[0]=="весовой" else "штучный (шт)",
                     "изм_2023": a[c], "выр_2023": round(r[c], 2),
                     "ранг_группа_изм": int(ri[c]), "ранг_группа_выр": int(rr[c]),
                     "в_2026_по_коду": c in y26_codes,
                     "последняя_продажа": str(df[df["Код "]==c]["День"].max().date())})
t = pd.DataFrame(rows)
lost = t[~t["в_2026_по_коду"]].copy()                    # 18 потерь по критерию

# ---------- 2. Читаем оба файла ----------
A = pd.read_excel(FILE_A, sheet_name="Потерянные_топы")
A["код"] = A["Код"].astype(str).str.strip().str.zfill(5)
A_set = set(A["код"])
B = pd.read_excel(FILE_B, sheet_name=None)
B_rows = []
for sh, tb in B.items():
    if sh.startswith("Ушедшие из топа"):
        tb = tb.copy()
        tb["код"] = tb["Код товара"].astype(str).str.strip().str.zfill(5)
        B_rows.append(tb)
B = pd.concat(B_rows, ignore_index=True)
B_set = set(B["код"])

# ---------- 3. Истина о рангах «по штукам» для весовых/штучных ----------
def rank_meta(code):
    rec = lost[lost["код"] == code].iloc[0]
    g = rec["группа"]
    p = y23[y23["группа"] == g].groupby("Код ")
    a = p["ТО, в е.изм."].sum(); r = p["ТО, руб"].sum()
    ri_all = a.rank(ascending=False, method="min").astype(int)
    rr_all = r.rank(ascending=False, method="min").astype(int)
    return int(ri_all[code]), int(rr_all[code])

# ---------- 4. Сводная сверка по коду ----------
lst = []
for _, rec in lost.iterrows():
    c = rec["код"]
    inA, inB = c in A_set, c in B_set
    # ранг из файла B (если есть)
    b_rank = (None, None)
    if inB:
        b = B[B["код"] == c].iloc[0]
        b_rank = (int(b["Ранг по штукам"]), int(b["Ранг по выручке"]))
    r_all = rank_meta(c)
    lst.append({"Код": c, "Группа": rec["группа"], "Название": rec["название"],
                "Тип (по данным)": rec["тип"],
                "Продано в 2023, ед.:": round(rec["изм_2023"], 1),
                "Выручка 2023, руб": rec["выр_2023"],
                "Есть в файле A (наш отчёт)": "да" if inA else "нет",
                "Есть в файле B (20260812)": "да" if inB else "нет",
                "Ранг по объёму, по всей группе": r_all[0],
                "Ранг по выручке, по всей группе": r_all[1],
                "Ранг по штукам, файл B": b_rank[0],
                "Ранг по выручке, файл B": b_rank[1],
                "Совпадает ранг B с групповым": "да" if (inB and b_rank == r_all) else
                    ("нет (B ранжирует среди кандидатов)" if inB else "—"),
                "Продажи в 2026 (по коду)": "нет" if not rec["в_2026_по_коду"] else "ЕСТЬ!",
                "Последняя продажа": rec["последняя_продажа"],
                "Статус в файле A": rec.get("Статус", "—")})
sv = pd.DataFrame(lst)

