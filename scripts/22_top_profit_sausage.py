# -*- coding: utf-8 -*-
"""
22_top_profit_sausage.py — ТОП по валовой прибыли (наценке) за всё время
=======================================================================
Задача пользователя: период 01.01.2023 – 10.08.2026, показать, по какой
колбасе мы больше всего ЗАРАБОТАЛИ — топ по наценке (валовой прибыли).

Что такое «Наценка» в файле: колонка «Наценка» на строку = валовая
прибыль = ТО руб − себестоимость (закупка). Складывая её по товару,
получаем, сколько рублей прибыли товар принёс за весь период.
«Наценка, %» = прибыль / выручка (доля каждого рубля выручки,
оставшаяся в кассе после закупки).

Логика (как в отчёте 19, но по прибыли):
  1) агрегат по товару за весь период: продано (шт/кг), выручка, прибыль;
  2) единицы честные: тип продажи (весовой — кг, штучный — шт) по данным,
     рядом «≈ кг» (шт × фасовка / 1000) для сравнения;
  3) лист «Топ» — общий топ-20 по прибыли; «По_группам» — топ-5 в каждой
     из 7 групп; «Сводка» — прибыль по группам; «Где_теряем» — товары
     с отрицательной наценкой (акции ниже закупки), если такие есть.

Выход: output/Отчет_топ_прибыли_колбаса.xlsx
"""

import re
import numpy as np
import pandas as pd

# ---------------------------------------------------------------
# Чтение
# ---------------------------------------------------------------
df = pd.read_excel(
    "data/колбасаНФ.xlsx",
    dtype={"Код ": str},
    parse_dates=["День"],
)
df = df.rename(columns={"Код ": "Код"})

s = df[(df["ТО, в е.изм."] > 0) & (df["ТО, руб"] > 0)].copy()
print(f"Строк в работе: {len(s)}, период: {s['День'].min().date()} – {s['День'].max().date()}")

# ---------------------------------------------------------------
# Тип продажи (весовой / штучный) — по данным за весь период
# ---------------------------------------------------------------
typ_s = s.groupby("Код")["ТО, в е.изм."].apply(
    lambda v: "весовой, кг" if ((v - np.floor(v)) > 1e-9).any() else "штучный, шт"
)

def parse_weight(name):
    m = re.search(r"(\d+(?:[.,]\d+)?)\s*(г|кг)\b", name)
    if not m:
        return None
    v = float(m.group(1).replace(",", "."))
    return v * 1000 if m.group(2) == "кг" else v

names = s.groupby("Код")["Номенклатура"].first()
weights = names.apply(parse_weight)          # фасовка в граммах (или NaN)

# ---------------------------------------------------------------
# Агрегат по товару за ВЕСЬ период
# ---------------------------------------------------------------
agg = (
    s.groupby(["группа", "Код", "Номенклатура"])
    .agg(
        Кол_ед=("ТО, в е.изм.", "sum"),
        Выручка_руб=("ТО, руб", "sum"),
        Прибыль_руб=("Наценка", "sum"),
    )
    .reset_index()
)
agg["Тип"] = agg["Код"].map(typ_s)
agg["Фасовка_г"] = agg["Код"].map(weights)

# «Продано ≈ кг»: у штучных шт × фасовка/1000, у весовых — кг
agg["Эквив_кг"] = agg["Кол_ед"].astype(float)
sh = (agg["Тип"] == "штучный, шт") & agg["Фасовка_г"].notna()
agg.loc[sh, "Эквив_кг"] = agg.loc[sh, "Кол_ед"] * agg.loc[sh, "Фасовка_г"] / 1000.0

# Ранг по прибыли внутри группы (для листа «по группам»)
agg["Ранг_прибыли_в_группе"] = agg.groupby("группа")["Прибыль_руб"].rank(
    method="min", ascending=False
).astype(int)

# Кто продавался в 2026 (для колонки «В продаже 2026»)
codes26 = set(s[s["День"].dt.year == 2026]["Код"].unique())

# ---------------------------------------------------------------
# Человеческие колонки
# ---------------------------------------------------------------
def kol_disp(vals, types):
    """Продано в собственных единицах: штучные — целое число, весовые — 1 знак."""
    res = vals.astype(float).copy()
    res[types == "штучный, шт"] = vals[types == "штучный, шт"].round(0)
    res[types == "весовой, кг"] = vals[types == "весовой, кг"].round(1)
    return res

def human(df_, add_cols):
    out = df_.copy()
    out["Тип продажи"] = out["Тип"]
    out["Продано за всё время (шт/кг)"] = kol_disp(out["Кол_ед"], out["Тип"])
    out["Продано ≈ кг"] = out["Эквив_кг"].round(1)
    out["Выручка, руб"] = out["Выручка_руб"].round(2)
    out["Валовая прибыль, руб"] = out["Прибыль_руб"].round(2)
    out["Наценка, % от выручки"] = (out["Прибыль_руб"] / out["Выручка_руб"] * 100).round(1)
    out["В продаже 2026"] = np.where(out["Код"].isin(codes26), "да", "НЕТ")
    cols = ["Группа", "Код", "Название товара", "Тип продажи",
            "Продано за всё время (шт/кг)", "Продано ≈ кг",
            "Выручка, руб", "Валовая прибыль, руб", "Наценка, % от выручки",
            "В продаже 2026"] + add_cols
    return out.rename(columns={"группа": "Группа", "Номенклатура": "Название товара"})[cols]

# ---------------------------------------------------------------
# Лист 1: общий топ-20 по валовой прибыли
# ---------------------------------------------------------------
top20 = agg.sort_values("Прибыль_руб", ascending=False).head(20).reset_index(drop=True)
top20.insert(0, "Место", range(1, len(top20) + 1))
t_top20 = human(top20, ["Место"])
t_top20 = t_top20[["Место"] + [c for c in t_top20.columns if c != "Место"]]

# ---------------------------------------------------------------
# Лист 2: топ-5 по прибыли в каждой группе
# ---------------------------------------------------------------
top5_g = agg[agg["Ранг_прибыли_в_группе"] <= 5].sort_values(
    ["группа", "Ранг_прибыли_в_группе"]
).reset_index(drop=True)
t_top5 = human(top5_g, ["Ранг_прибыли_в_группе"])
t_top5 = t_top5.rename(columns={"Ранг_прибыли_в_группе": "Место в группе"})

# ---------------------------------------------------------------
# Лист 3: сводка по группам
# ---------------------------------------------------------------
gr = (
    agg.groupby("группа")
    .agg(
        Товаров=("Код", "nunique"),
        Продано_кг=("Эквив_кг", "sum"),
        Выручка=("Выручка_руб", "sum"),
        Прибыль=("Прибыль_руб", "sum"),
    )
    .reset_index()
    .sort_values("Прибыль", ascending=False)
)
tot_v, tot_p = gr["Выручка"].sum(), gr["Прибыль"].sum()
gr["Доля в прибыли, %"] = (gr["Прибыль"] / tot_p * 100).round(1)
gr["Наценка, % от выручки"] = (gr["Прибыль"] / gr["Выручка"] * 100).round(1)
t_groups = gr.rename(columns={
    "группа": "Группа",
    "Товаров": "Товаров за период",
    "Продано_кг": "Продано ≈ кг (всего)",
    "Выручка": "Выручка, руб",
    "Прибыль": "Валовая прибыль, руб",
})
t_groups["Выручка, руб"] = t_groups["Выручка, руб"].round(2)
t_groups["Валовая прибыль, руб"] = t_groups["Валовая прибыль, руб"].round(2)
t_groups["Продано ≈ кг (всего)"] = t_groups["Продано ≈ кг (всего)"].round(1)
t_groups = t_groups[["Группа", "Товаров за период", "Продано ≈ кг (всего)",
                     "Выручка, руб", "Валовая прибыль, руб",
                     "Доля в прибыли, %", "Наценка, % от выручки"]]

# ---------------------------------------------------------------
# Лист 4: где теряем (отрицательная наценка за период)
# ---------------------------------------------------------------
neg = agg[agg["Прибыль_руб"] < 0].sort_values("Прибыль_руб").reset_index(drop=True)
neg.insert(0, "Место", range(1, len(neg) + 1))
if len(neg):
    t_neg = human(neg, ["Место"])
    t_neg = t_neg[["Место"] + [c for c in t_neg.columns if c != "Место"]]
else:
    t_neg = pd.DataFrame({"Пояснение": ["Товаров с отрицательной наценкой за период нет"]})

# ---------------------------------------------------------------
# Печать
# ---------------------------------------------------------------
print("=" * 78)
print("ТОП-10 ПО ВАЛОВОЙ ПРИБЫЛИ (наценка) ЗА ВЕСЬ ПЕРИОД 2023-01-01–2026-08-10")
print("=" * 78)
for _, r in top20.head(10).iterrows():
    mark = "" if r["Код"] in codes26 else "  [в 2026 НЕТ]"
    print(f"  {r['Прибыль_руб']:>12,.0f} руб  {r['Выручка_руб']:>12,.0f} руб  "
          f"{r['Номенклатура'][:46]}{mark}")

print(f"\nВСЕГО за период: выручка {tot_v:,.0f} руб, валовая прибыль {tot_p:,.0f} руб, "
      f"наценка к выручке {tot_p / tot_v * 100:.1f}%")
print("\nПо группам (вал. прибыль, доля, наценка %):")
for _, r in t_groups.iterrows():
    print(f"  {r['Группа']:<24} {r['Валовая прибыль, руб']:>12,.0f} руб  "
          f"{r['Доля в прибыли, %']:>5.1f}%  наценка {r['Наценка, % от выручки']:.1f}%")
print(f"\nТоваров с отрицательной наценкой (теряем): {len(neg)}")

# ---------------------------------------------------------------
# Сверка с исходником
# ---------------------------------------------------------------
check_sum = float(s["Наценка"].sum())
assert abs(check_sum - float(agg["Прибыль_руб"].sum())) < 1e-6, "Сверка суммы наценки не сошлась!"
check_rev = float(s["ТО, руб"].sum())
assert abs(check_rev - float(agg["Выручка_руб"].sum())) < 1e-6, "Сверка выручки не сошлась!"
print(f"Сверка с исходником: наценка {agg['Прибыль_руб'].sum():,.0f} = {check_sum:,.0f} ✓, "
      f"выручка {agg['Выручка_руб'].sum():,.0f} = {check_rev:,.0f} ✓")

# ---------------------------------------------------------------
# Сохранение
# ---------------------------------------------------------------
OUT = "output/Отчет_топ_прибыли_колбаса.xlsx"
with pd.ExcelWriter(OUT, engine="openpyxl") as writer:
    t_top20.to_excel(writer, sheet_name="Топ_по_валовой_прибыли", index=False)
    t_top5.to_excel(writer, sheet_name="Топ_прибыли_по_группам", index=False)
    t_groups.to_excel(writer, sheet_name="Сводка_по_группам", index=False)
    t_neg.to_excel(writer, sheet_name="Где_теряем", index=False)
    pd.DataFrame({
        "Шаг": ["Период", "Источник", "Показатель", "Единицы", "Наценка %"],
        "Пояснение": [
            "01.01.2023 – 10.08.2026 (все строки файла колбасаНФ.xlsx с ТО>0 и ТО руб>0)",
            "Колонка «Наценка» на строку = валовая прибыль (ТО руб − себестоимость/закупка)",
            "«Валовая прибыль, руб» = сумма наценки по товару за период; «Наценка, % от выручки» = прибыль / выручка × 100",
            "весовые товары — кг, штучные — шт (тип по данным: есть дробная продажа → весовой); «≈ кг» = шт × фасовка/1000",
            "Убыток (отрицательная наценка) = продажи по акции ниже закупки; такие товары в листе «Где_теряем»",
        ],
    }).to_excel(writer, sheet_name="Методика", index=False)

print(f"\nСохранено: {OUT}")
print(f"  Лист «Топ_по_валовой_прибыли»: {len(t_top20)} строк (общий топ-20)")
print(f"  Лист «Топ_прибыли_по_группам»: {len(t_top5)} строк (топ-5 в каждой группе)")
print(f"  Лист «Сводка_по_группам»: {len(t_groups)} строк")
print(f"  Лист «Где_теряем»: {len(t_neg)} строк")
print("  Лист «Методика»: пояснения")