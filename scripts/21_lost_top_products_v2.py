# -*- coding: utf-8 -*-
"""
21_lost_top_products_v2.py — Потерянные топ-товары 2023 и 2024 (версия 2)
========================================================================
Что исправлено против скриптов 16/17 (пересчёт по замечанию пользователя):

  1) ЕДИНИЦЫ. Раньше штучные товары (шт) и весовые (кг) стояли в одном
     ранге «по объёму», как будто 1 шт = 1 кг. Теперь каждый товар
     считается в СВОИХ единицах: весовой — в кг, штучный — в шт.
     Это честнее: у штучного товара 10 000 шт — это НЕ «10 000 кг».
  2) Тип продажи определяется по данным за весь период: есть хоть одна
     дробная продажа (0,45 кг) — товар весовой; все продажи целые — штучный.
  3) Чтобы объёмы разных типов всё же можно было сравнить «вниз по таблице»,
     рядом добавлен столбец «≈ кг» (у штучных: шт × фасовка / 1000).
  4) Старые файлы отчётов 16/17 НЕ трогаем — новые сохраняются как _v2.

Логика поиска потерь — прежняя (проверена в 16/17):
  1) за базовый год (2023 или 2024) по каждой группе ранжируем товары
     по количеству (в собственных единицах) и по выручке (руб);
  2) топ = первые 10; «звёзды» = пересечение двух топов;
  3) потерянные = звёзды без продаж в 2026 (по коду);
  4) поиск «продолжений» по правилу шринкфляции: тот же товар, сменивший
     фасовку/код (ядро названия + зазор дат). Шринкфляция = товар ЖИВ.

Выход:
  output/Отчет_потерянные_топы_2023_2026_v2.xlsx
  output/Отчет_потерянные_топы_2024_2026_v2.xlsx
"""

import re
import numpy as np
import pandas as pd

# ---------------------------------------------------------------
# Чтение
# ---------------------------------------------------------------
df = pd.read_excel(
    "data/колбасаНФ.xlsx",
    dtype={"Код ": str},
    parse_dates=["День"],
)
df = df.rename(columns={"Код ": "Код"})

s = df[(df["ТО, в е.изм."] > 0) & (df["ТО, руб"] > 0)].copy()
y26 = s[s["День"].dt.year == 2026]

# ---------------------------------------------------------------
# Ядро названия: без фасовки и маркеров упаковки (в/у, п/к и т.п.)
# ---------------------------------------------------------------
def parse_weight(name):
    m = re.search(r"(\d+(?:[.,]\d+)?)\s*(г|кг)\b", name)
    if not m:
        return None
    v = float(m.group(1).replace(",", "."))
    return v * 1000 if m.group(2) == "кг" else v

def core_name(name):
    name = re.sub(r"\d+(?:[.,]\d+)?\s*(г|кг)\b", "", name)
    name = re.sub(r"\s*(?:в/у|в/с|в/к|п/к|с/у|бзмж)\b", " ", name)
    name = re.sub(r"\s+", " ", name).strip()
    return name

# ---------------------------------------------------------------
# Тип продажи (весовой / штучный) — по данным за ВЕСЬ период
# ---------------------------------------------------------------
# Аналогия: весовой товар продаётся «на развес» — бывают продажи 0,45 кг;
# штучный — только целыми упаковками (коробками, батонами).
typ_s = s.groupby("Код")["ТО, в е.изм."].apply(
    lambda v: "весовой, кг" if ((v - np.floor(v)) > 1e-9).any() else "штучный, шт"
)

# Справочники по коду
names = s.groupby("Код")["Номенклатура"].first()
weights = names.apply(parse_weight)          # фасовка в граммах (или NaN)
last_sale = s.groupby("Код")["День"].max()
first_sale_all = s.groupby("Код")["День"].min()
first_name = s.groupby("Код")["Номенклатура"].first()
codes26 = set(y26["Код"].unique())
y26_sum = y26.groupby("Код")["ТО, в е.изм."].sum()

# Справочник «живых» 2026: код → (ядро, вес, первая продажа за весь период, группа)
alive = {}
g26 = y26.groupby("Код")["группа"].first()
for code in codes26:
    nm = first_name[code]
    alive[code] = {
        "ядро": core_name(nm),
        "вес": parse_weight(nm),
        "первая_продажа": first_sale_all[code],
        "название": nm,
        "группа": g26[code],
    }

# Общие слова (тип продукта) — не считаем их «отличительными»
STOP_WORDS = {
    "молочная", "молочные", "вареная", "варенокопченая", "сырокопченая",
    "полукопченая", "копченая", "колбаса", "ветчина", "сосиски",
    "шпикачки", "сардельки", "сервелат", "вареный",
}
BRAND_RE = re.compile(r"[А-ЯЁ]{2,}(?:\s+[А-ЯЁ]{2,})*")

# ---------------------------------------------------------------
# Функции форматирования под тип продажи
# ---------------------------------------------------------------
def kol_disp(vals, types):
    """Продано в собственных единицах: штучные — целое число, весовые — 1 знак."""
    res = vals.astype(float).copy()
    res[types == "штучный, шт"] = vals[types == "штучный, шт"].round(0)
    res[types == "весовой, кг"] = vals[types == "весовой, кг"].round(1)
    return res

def equiv_kg(vals, types, w):
    """Честное сравнение объёмов: штучные → шт × фасовка/1000, весовые → кг."""
    kg = vals.astype(float).copy()
    sh = (types == "штучный, шт") & w.notna()
    kg[sh] = vals[sh] * w[sh] / 1000.0
    return kg

# ---------------------------------------------------------------
# Поиск продолжений по правилу пользователя (шринкфляция)
# ---------------------------------------------------------------
def find_pairs(r):
    """Ищем в 2026 позиции с тем же ядром названия и разумным зазором."""
    core = core_name(r["Номенклатура"])
    old_w = parse_weight(r["Номенклатура"])
    last_d = last_sale[r["Код"]]
    cands = []
    for code, info in alive.items():
        if info["ядро"] != core:
            continue
        gap = (info["первая_продажа"] - last_d).days
        # −60: старая и новая фасовка могли продаваться параллельно (остатки);
        # +730: продолжение могло вернуться после долгого перерыва
        if gap < -60 or gap > 730:
            continue
        cands.append((gap, code, info))
    if not cands:
        return None, None, None, None, "ядро"
    cands.sort(key=lambda x: x[0])
    gap, code, info = cands[0]
    return code, info, gap, old_w, "ядро"


def find_pairs_lenient(r):
    """Мягкий поиск: тот же бренд и отличительное слово в той же группе.

    Ловит переименования с маркетинговой приставкой, когда ядро названия
    не совпало. Пример из данных: «Сервелат ТОРГОВАЯ ПЛОЩАДЬ Министерский
    в/к 320г» → «Сервелат ТОРГОВАЯ ПЛОЩАДЬ Как тогда Министерский в/к 270г»
    (бренд один, а приставка «Как тогда» сломала сравнение ядер).
    """
    name = r["Номенклатура"]
    old_w = parse_weight(name)
    last_d = last_sale[r["Код"]]
    m = BRAND_RE.search(name)
    brand = m.group(0) if m else ""
    brand_tokens = {t.lower() for t in brand.split()}
    sig = [
        w for w in re.findall(r"[А-Яа-яЁё]{6,}", name)
        if w.lower() not in brand_tokens and w.lower() not in STOP_WORDS
    ]
    cands = []
    for code, info in alive.items():
        if info["группа"] != r["группа"]:
            continue
        if brand and brand not in info["название"]:
            continue
        if not any(w in info["название"] for w in sig):
            continue
        gap = (info["первая_продажа"] - last_d).days
        if gap < -480 or gap > 730:
            continue
        cands.append((gap, code, info))
    if not cands:
        return None, None, None, None, "мягкий"
    cands.sort(key=lambda x: x[0])
    gap, code, info = cands[0]
    return code, info, gap, old_w, "мягкий"


# ---------------------------------------------------------------
# Обработка одного базового года
# ---------------------------------------------------------------
TOP_N = 10

def process_year(base_year):
    yb = s[s["День"].dt.year == base_year]

    agg = (
        yb.groupby(["группа", "Код", "Номенклатура"])
        .agg(
            Кол_ед=("ТО, в е.изм.", "sum"),
            Выручка_руб=("ТО, руб", "sum"),
            Дней_продаж=("День", "nunique"),
        )
        .reset_index()
    )
    agg["Тип"] = agg["Код"].map(typ_s)
    agg["Фасовка_г"] = agg["Код"].map(weights)
    agg["Эквив_кг"] = equiv_kg(agg["Кол_ед"], agg["Тип"], agg["Фасовка_г"])

    # Ранги в собственных единицах: штучные — по штукам, весовые — по кг
    agg["Ранг_по_количеству"] = agg.groupby("группа")["Кол_ед"].rank(
        method="min", ascending=False
    ).astype(int)
    agg["Ранг_по_выручке"] = agg.groupby("группа")["Выручка_руб"].rank(
        method="min", ascending=False
    ).astype(int)

    top_q = agg[agg["Ранг_по_количеству"] <= TOP_N]
    top_r = agg[agg["Ранг_по_выручке"] <= TOP_N]

    # «Звёзды»: топ и по количеству, и по выручке
    stars = top_q.merge(top_r[["группа", "Код"]], on=["группа", "Код"], how="inner")

    # Потерянные по коду: в 2026 нет продаж
    stars["Продано_2026_ед"] = stars["Код"].map(y26_sum).fillna(0.0)
    lost = stars[stars["Продано_2026_ед"] == 0].copy()

    # Когда товар продавался в последний раз (по всем годам)
    lost["Последняя продажа"] = lost["Код"].map(last_sale).dt.date

    # Пустые слоты для колонок продолжения
    lost["Статус"] = ""
    lost["Продолжение"] = ""
    lost["Продано_2026_прод_ед"] = np.nan
    lost["Продано_2026_прод_кг"] = np.nan
    lost["Тип_продолжения"] = np.nan
    lost["Первая_продажа_продолжения"] = ""
    lost["Зазор_дней"] = np.nan
    lost["Новая_фасовка_г"] = np.nan
    lost["Как найден"] = ""

    for i, r in lost.iterrows():
        old_w = parse_weight(r["Номенклатура"])
        lost.at[i, "Старая_фасовка_г"] = old_w
        r["Старая_фасовка_г"] = old_w
        code_new, info, gap, _, method = find_pairs(r)
        if info is None:
            code_new, info, gap, _, method = find_pairs_lenient(r)
        if info is None:
            lost.at[i, "Статус"] = "исчез"
            continue
        new_w = info["вес"]
        if old_w is not None and new_w is not None and new_w < old_w and (gap <= 180 or gap < 0):
            status = "шринкфляция (продолжение)"
        elif old_w is not None and new_w is not None and new_w < old_w:
            status = f"продолжение, но зазор {gap} дн"
        elif old_w is not None and new_w is not None and new_w == old_w:
            status = "перекодировка (продолжение)"
        elif old_w is not None and new_w is not None and new_w > old_w:
            status = "продолжение? (фасовка БОЛЬШЕ)"
        else:
            status = "продолжение? (вес не определён)"
        lost.at[i, "Статус"] = status
        lost.at[i, "Продолжение"] = f"{code_new} «{info['название'][:50]}»"
        lost.at[i, "Первая_продажа_продолжения"] = info["первая_продажа"].date()
        lost.at[i, "Зазор_дней"] = gap
        lost.at[i, "Новая_фасовка_г"] = new_w
        lost.at[i, "Как найден"] = "ядро названия" if method == "ядро" else "бренд + тип (мягкий)"
        # Продажи продолжения в 2026 — в его собственных единицах и «≈ кг»
        v26 = y26_sum.get(code_new, 0.0)
        t26 = typ_s.get(code_new)
        w26 = weights.get(code_new)
        if t26 == "штучный, шт" and w26 is not None and pd.notna(w26):
            kg26 = v26 * w26 / 1000.0
        else:
            kg26 = v26
        lost.at[i, "Продано_2026_прод_ед"] = v26
        lost.at[i, "Продано_2026_прод_кг"] = kg26
        lost.at[i, "Тип_продолжения"] = t26

    # ---------------------------------------------------------
    # Итоговая таблица
    # ---------------------------------------------------------
    out = lost.sort_values(["группа", "Ранг_по_количеству"]).reset_index(drop=True)
    out = out.rename(
        columns={
            "группа": "Группа",
            "Код": "Код",
            "Номенклатура": "Название товара",
            "Тип": "Тип продажи",
            "Ранг_по_количеству": f"Место по продажам в {base_year} (шт/кг)",
            "Кол_ед": f"Продано в {base_year} (шт/кг)",
            "Эквив_кг": f"Продано в {base_year} ≈ кг",
            "Ранг_по_выручке": f"Место по выручке в {base_year}",
            "Выручка_руб": f"Выручка в {base_year}, руб",
            "Дней_продаж": f"Дней с продажами в {base_year}",
            "Последняя продажа": "Последняя дата продажи",
            "Продолжение": "Продолжение в 2026 (код и название)",
            "Первая_продажа_продолжения": "Первая продажа продолжения",
            "Зазор_дней": "Зазор, дней",
            "Старая_фасовка_г": "Фасовка старая, г",
            "Новая_фасовка_г": "Фасовка новая, г",
            "Как найден": "Как найдено продолжение",
        }
    )
    out[f"Продано в {base_year} (шт/кг)"] = kol_disp(out[f"Продано в {base_year} (шт/кг)"], out["Тип продажи"])
    out[f"Продано в {base_year} ≈ кг"] = out[f"Продано в {base_year} ≈ кг"].round(1)
    out[f"Выручка в {base_year}, руб"] = out[f"Выручка в {base_year}, руб"].round(2)
    out["Продано в 2026 (продолжение, шт/кг)"] = kol_disp(
        out["Продано_2026_прод_ед"], out["Тип_продолжения"].fillna("штучный, шт")
    )
    out["Продано в 2026 ≈ кг"] = out["Продано_2026_прод_кг"].round(1)

    cols = [
        "Группа", "Код", "Название товара", "Тип продажи",
        f"Место по продажам в {base_year} (шт/кг)",
        f"Продано в {base_year} (шт/кг)", f"Продано в {base_year} ≈ кг",
        f"Место по выручке в {base_year}", f"Выручка в {base_year}, руб",
        f"Дней с продажами в {base_year}", "Последняя дата продажи",
        "Статус", "Продолжение в 2026 (код и название)",
        "Продано в 2026 (продолжение, шт/кг)", "Продано в 2026 ≈ кг",
        "Первая продажа продолжения", "Зазор, дней",
        "Фасовка старая, г", "Фасовка новая, г", "Как найдено продолжение",
    ]
    out = out[cols]
    for col in ["Продано в 2026 (продолжение, шт/кг)", "Продано в 2026 ≈ кг",
                "Первая продажа продолжения", "Зазор, дней",
                "Фасовка новая, г", "Как найдено продолжение"]:
        out[col] = out[col].replace({"": "—"}).fillna("—")

    # ---------------------------------------------------------
    # Справочные листы: полные топы
    # ---------------------------------------------------------
    top_q_tbl = top_q.sort_values(["группа", "Ранг_по_количеству"]).copy()
    top_q_tbl["Тип продажи"] = top_q_tbl["Код"].map(typ_s)
    top_q_tbl[f"Продано в {base_year} (шт/кг)"] = kol_disp(top_q_tbl["Кол_ед"], top_q_tbl["Тип продажи"])
    top_q_tbl[f"Продано в {base_year} ≈ кг"] = top_q_tbl["Эквив_кг"].round(1)
    top_q_tbl["В продаже 2026"] = np.where(top_q_tbl["Код"].isin(codes26), "да", "НЕТ")
    top_q_tbl = top_q_tbl[["группа", "Код", "Номенклатура", "Тип продажи",
                           f"Продано в {base_year} (шт/кг)", f"Продано в {base_year} ≈ кг",
                           "В продаже 2026"]].rename(
        columns={"группа": "Группа", "Номенклатура": "Название товара"}
    )

    top_r_tbl = top_r.sort_values(["группа", "Ранг_по_выручке"]).copy()
    top_r_tbl["Тип продажи"] = top_r_tbl["Код"].map(typ_s)
    top_r_tbl[f"Выручка в {base_year}, руб"] = top_r_tbl["Выручка_руб"].round(2)
    top_r_tbl["В продаже 2026"] = np.where(top_r_tbl["Код"].isin(codes26), "да", "НЕТ")
    top_r_tbl = top_r_tbl[["группа", "Код", "Номенклатура", "Тип продажи",
                           f"Выручка в {base_year}, руб", "В продаже 2026"]].rename(
        columns={"группа": "Группа", "Номенклатура": "Название товара"}
    )

    return out, top_q_tbl, top_r_tbl

# ---------------------------------------------------------------
# Прогон по обоим базовым годам + сверка со старой версией
# ---------------------------------------------------------------
for base_year in (2023, 2024):
    out, top_q_tbl, top_r_tbl = process_year(base_year)

    print("=" * 78)
    print(f"ТОП-ТОВАРЫ {base_year}, КОТОРЫХ НЕТ В ПРОДАЖАХ 2026 (по коду) — по группам")
    print("=" * 78)
    for g, grp in out.groupby("Группа"):
        print(f"\n— {g}:")
        for _, r in grp.iterrows():
            tail = f"→ {r['Продолжение в 2026 (код и название)']}" if r["Статус"] != "исчез" else ""
            print(f"  [{r['Статус'][:14]:<14}] {r['Название товара'][:48]} {tail}")

    print("\nИтого:", len(out), "«звёзд» без продаж 2026 по коду:")
    print(out["Статус"].value_counts().to_string())

    # Сверка со старой версией (16/17): кто добавился / ушёл из списка потерь
    v1 = f"output/Отчет_потерянные_топы_{base_year}_2026.xlsx"
    try:
        old_codes = set(pd.read_excel(v1, sheet_name="Потерянные_топы")["Код"].astype(str))
        new_codes = set(out["Код"].astype(str))
        print(f"\nСверка со старой версией {v1}:")
        print(f"  Было строк: {len(old_codes)}, стало: {len(new_codes)}")
        added = sorted(new_codes - old_codes)
        removed = sorted(old_codes - new_codes)
        if added:
            print("  Добавились в список потерь:", ", ".join(added))
        if removed:
            print("  Ушли из списка потерь:", ", ".join(removed))
        if not added and not removed:
            print("  Состав списка потерь не изменился.")
    except FileNotFoundError:
        print(f"\n(Старая версия {v1} не найдена — сверка пропущена)")

    OUT = f"output/Отчет_потерянные_топы_{base_year}_2026_v2.xlsx"
    with pd.ExcelWriter(OUT, engine="openpyxl") as writer:
        out.to_excel(writer, sheet_name="Потерянные_топы", index=False)
        top_q_tbl.to_excel(writer, sheet_name=f"Топ-10_по_количеству_{base_year}", index=False)
        top_r_tbl.to_excel(writer, sheet_name=f"Топ-10_по_выручке_{base_year}", index=False)

    print(f"\nСохранено: {OUT}")
    print(f"  Лист «Потерянные_топы»: {len(out)} строк")
    print(f"  Лист «Топ-10_по_количеству_{base_year}»: {len(top_q_tbl)} строк")
    print(f"  Лист «Топ-10_по_выручке_{base_year}»: {len(top_r_tbl)} строк")