# Сводка по коду за год
# ---------------------------------------------------------------
agg = (
    y.groupby(["группа", "Код"])
    .agg(
        Название=("Номенклатура", "first"),
        Выручка_руб=("ТО, руб", "sum"),
        Продано_кг=("ТО, в е.изм.", "sum"),
        Наценка_руб=("Наценка", "sum"),
        Дней_продаж=("День", "nunique"),
    )
    .reset_index()
)
print(f"Товаров за год: {len(agg)} | групп: {agg['группа'].nunique()}")

# ---------------------------------------------------------------
# Тип продажи (ПОПРАВКА пользователя): в данных два типа товаров.
# Весовой — продажа резаная, значения дробные (напр. 1,786 кг):
#    00814 «Любительская в синюге в/с 1кг» = взвесили кусок.
# Штучный — целое число упаковок (напр. 10 шт по 350 г):
#    210935 «Филейская с шпиком вареная 350г» = 10 упаковок.
# Правило определения: хотя бы одна дробная продажа → весовой, кг;
# все продажи целые → штучный, шт.
# ---------------------------------------------------------------
prod_type = y.groupby("Код")["ТО, в е.изм."].apply(
    lambda v: "весовой, кг" if ((v - np.floor(v)) > 1e-9).any() else "штучный, шт"
)
agg["Тип"] = agg["Код"].map(prod_type)

# Фасовка штучных — из названия (350г → 0,35 кг): нужна для «≈ кг»-сравнения
agg["Фасовка_г"] = agg["Название"].map(parse_weight)
agg["Эквивалент_кг"] = agg["Продано_кг"].astype(float)
sh_kg = agg["Тип"] == "штучный, шт"
agg.loc[sh_kg, "Эквивалент_кг"] = (
    agg.loc[sh_kg, "Продано_кг"] * agg.loc[sh_kg, "Фасовка_г"] / 1000
)
# отдельные суммы для итогов по группам (кг у весовых, шт у штучных)
agg["Продано_весовых_кг"] = np.where(agg["Тип"] == "весовой, кг", agg["Продано_кг"], 0.0)
agg["Продано_штучных_шт"] = np.where(agg["Тип"] == "штучный, шт", agg["Продано_кг"], 0.0)
