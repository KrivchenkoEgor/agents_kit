"""
18_abc_sausage.py — ABC-анализ колбасы по группам (выручка, объём, наценка)
==========================================================================
Задача пользователя: в каждой группе товаров сделать ABC-анализ по
товарообороту в рублях, товарообороту (вес, кг — колбаса продаётся
на вес, «штук» в данных нет) и наценке за последний год, показать
объединённый результат. Каждый показатель — на отдельной странице Excel.

Логика ABC (правило 80/20, классика):
  внутри каждой группы товары сортируются по показателю по убыванию;
  классы по накопленной доле: A — первые 80%, B — до 95%, C — остальные 5%.

Период «последний год»: последние 365 дней данных (11.08.2025 – 10.08.2026).

Листы отчёта (output/Отчет_ABC_колбаса_группы.xlsx):
  1. ABC_по_выручке_руб    — классы внутри групп по ТО руб
  2. ABC_по_объёму_кг        — классы внутри групп по ТО, кг
  3. ABC_по_наценке_руб     — классы внутри групп по Наценка (валовая прибыль)
  4. Объединенный_результат — по строке на товар: все три класса + заметка
  5. Итоги_по_группам       — сколько A/B/C по каждому показателю в группе
  6. ABC_общий_по_магазину  — весь ассортимент единым пулом (те же 3 показателя)
  7. Методика               — как считали
"""

import re
import numpy as np
import pandas as pd

# ---------------------------------------------------------------
# Чтение
# ---------------------------------------------------------------
df = pd.read_excel(
    "data/колбасаНФ.xlsx",
    dtype={"Код ": str},
    parse_dates=["День"],
)
df = df.rename(columns={"Код ": "Код"})

# только «настоящие» продажи (возвраты и нули исключаем из объёмов;
# отрицательная наценка (продажа ниже закупки — акции) остаётся в сумме!
s = df[(df["ТО, в е.изм."] > 0) & (df["ТО, руб"] > 0)].copy()

# ---------------------------------------------------------------
# Период: последний полный год данных
# ---------------------------------------------------------------
end = s["День"].max()                  # 10.08.2026
start = end - pd.Timedelta(days=364)   # ровно 365 дней включительно
y = s[(s["День"] >= start) & (s["День"] <= end)]
print(f"Период: {start.date()} … {end.date()} ({len(y):,} строк продаж)".replace(",", " "))

# ---------------------------------------------------------------
# Фасовка из названия (350г → 350; «1кг» → 1000) — для перевода
# штучных товаров в «≈ кг»
# ---------------------------------------------------------------
def parse_weight(name):
    m = re.search(r"(\d+(?:[.,]\d+)?)\s*(г|кг)\b", str(name))
    if not m:
        return None
    v = float(m.group(1).replace(",", "."))
    return v * 1000 if m.group(2) == "кг" else v

