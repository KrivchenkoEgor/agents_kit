# Лист 6: общий ABC по магазину (весь ассортимент единым пулом)
# ---------------------------------------------------------------
def abc_pool(tbl, value_col, out_col):
    tbl = tbl.sort_values(value_col, ascending=False).reset_index(drop=True)
    total = tbl[value_col].sum()
    tbl["Доля_в_магазине"] = tbl[value_col] / total
    tbl["Накопленная_доля"] = tbl["Доля_в_магазине"].cumsum()
    tbl["Место_в_магазине"] = np.arange(1, len(tbl) + 1)
    tbl[out_col] = np.where(
        tbl["Накопленная_доля"] <= 0.80, "A",
        np.where(tbl["Накопленная_доля"] <= 0.95, "B", "C"),
    )
    return tbl

