def sravnenie(row):
    """Заметка о сочетании классов — видно «звёзд» и «работающих зря»."""
    a, b, c = row["Класс_по_выручке"], row["Класс_по_объёму"], row["Класс_по_наценке"]
    if a == "A" and b == "A" and c == "A":
        return "ЗВЕЗДА: и касса, и объём, и прибыль"
    if a == "A" and c == "C":
        return "Акция/низкая маржа: продаётся много, зарабатывает мало"
    if a == "A" and b == "C":
        return "Дорогой товар: много рублей при малом весе"
    if a == "C" and b == "A":
        return "Дешёвый объём: много кг/шт при малой выручке"
    if a == "C" and c == "C":
        return "Аутсайдер по кассе и прибыли"
    return ""

