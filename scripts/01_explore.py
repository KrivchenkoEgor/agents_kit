# -*- coding: utf-8 -*-
"""
01_explore.py — Разведка данных: чтение файла целиком + базовая статистика
=========================================================================
Цель: понять, что лежит в файле, прежде чем решать, какие задачи решать.
Как инвентаризация склада перед планированием: смотрим ассортимент,
период, объёмы, топ-товары и динамику продаж по месяцам.

Вход:  data/Молоко.xlsx
Выход: печать отчёта в консоль (таблиц пока не сохраняем)
"""

import pandas as pd

# ---------------------------------------------------------------
# 1. Чтение файла
# ---------------------------------------------------------------
# Важно: колонку «Код номенклатуры» открываем как ТЕКСТ (str),
# иначе ведущие нули пропадут и «00014» превратится в «14».
FILE = "data/Молоко.xlsx"

df = pd.read_excel(
    FILE,
    dtype={"Код номенклатуры": str},  # коды — это текст, а не числа
    parse_dates=["День"],             # дату читаем как настоящую дату
)

print("=" * 70)
print("1. ОБЩАЯ ИНФОРМАЦИЯ")
print("=" * 70)
print(f"Строк (записей о продажах): {len(df):,}".replace(",", " "))
print(f"Колонки: {list(df.columns)}")
print(f"Типы данных:\n{df.dtypes}")

# ---------------------------------------------------------------
# 2. Пропуски и дубликаты
# ---------------------------------------------------------------
print("\n" + "=" * 70)
print("2. ПРОПУСКИ И ДУБЛИКАТЫ")
print("=" * 70)
print("Пустых значений по колонкам:")
print(df.isna().sum().to_string())

# Дубликат — это пара «код товара + день» встречается больше одного раза
dups = df.duplicated(subset=["Код номенклатуры", "День"]).sum()
print(f"\nДубликатов пар «товар + день»: {dups}")

# ---------------------------------------------------------------
# 3. Ассортимент и период
# ---------------------------------------------------------------
print("\n" + "=" * 70)
print("3. АССОРТИМЕНТ И ПЕРИОД")
print("=" * 70)
n_sku = df["Код номенклатуры"].nunique()
print(f"Уникальных товаров (SKU): {n_sku}")
print(f"Период данных: с {df['День'].min().date()} по {df['День'].max().date()}")
print(f"Всего дней в данных: {(df['День'].max() - df['День'].min()).days + 1}")

# ---------------------------------------------------------------
# 4. Итоговые объёмы
# ---------------------------------------------------------------
print("\n" + "=" * 70)
print("4. ИТОГОВЫЕ ОБЪЁМЫ")
print("=" * 70)
print(f"Всего продано, штук:  {df['ТО, в е.изм.'].sum():,.0f}".replace(",", " "))
print(f"Всего выручка, руб:   {df['ТО, руб'].sum():,.2f}".replace(",", " "))
print(f"Средний чек на запись: {df['ТО, руб'].mean():.2f} руб")
print(f"Дней с нулевой продажей: {(df['ТО, в е.изм.'] == 0).sum()}")

# ---------------------------------------------------------------
# 5. Топ-10 товаров по выручке и по штукам
# ---------------------------------------------------------------
print("\n" + "=" * 70)
print("5. ТОП-10 ТОВАРОВ")
print("=" * 70)

top_rub = (
    df.groupby("Номенклатура")["ТО, руб"]
    .sum()
    .sort_values(ascending=False)
    .head(10)
)
print("\nПо выручке (руб):")
for name, val in top_rub.items():
    print(f"  {val:>12,.0f}  {name}".replace(",", " "))

top_qty = (
    df.groupby("Номенклатура")["ТО, в е.изм."]
    .sum()
    .sort_values(ascending=False)
    .head(10)
)
print("\nПо количеству (штук):")
for name, val in top_qty.items():
    print(f"  {val:>12,.0f}  {name}".replace(",", " "))

# ---------------------------------------------------------------
# 6. Динамика выручки по месяцам
# ---------------------------------------------------------------
print("\n" + "=" * 70)
print("6. ДИНАМИКА ВЫРУЧКИ ПО МЕСЯЦАМ")
print("=" * 70)

monthly = (
    df.groupby(df["День"].dt.to_period("M"))
    .agg({"ТО, руб": "sum", "ТО, в е.изм.": "sum"})
)
for period, row in monthly.iterrows():
    print(f"  {period}  выручка: {row['ТО, руб']:>12,.0f} руб,  "
          f"штук: {row['ТО, в е.изм.']:>10,.0f}".replace(",", " "))

# ---------------------------------------------------------------
# 7. Средние продажи на товар в день (плотность)
# ---------------------------------------------------------------
print("\n" + "=" * 70)
print("7. НАСКОЛЬКО ПЛОТНО ПРОДАЁТСЯ КАЖДЫЙ ТОВАР")
print("=" * 70)
per_sku = df.groupby("Код номенклатуры").size()
print(f"Записей на товар: мин {per_sku.min()}, медиана {per_sku.median():.0f}, макс {per_sku.max()}")
print(f"Товаров с продажами во все дни периода: {(per_sku == per_sku.max()).sum()}")
print(f"Товаров, у которых записей < 10: {(per_sku < 10).sum()} (возможно, новинки или снятые)")

print("\n" + "=" * 70)
print("Разведка завершена. Следующие шаги — по решению пользователя.")
print("=" * 70)
