# -*- coding: utf-8 -*-
"""
11_group_c.py — Кто сидит в «хвосте» ассортимента (группа C)
=============================================================
Группа C по ABC-анализу — последние 5% выручки. Смотрим на каждый
такой товар: сколько даёт денег и штук, как давно в ассортименте,
продаётся ли вообще сейчас, растёт или угасает.

Статус товара:
  - «не продаётся 3+ мес» — мёртвый груз, кандидат на снятие с полки;
  - «новинка (до 12 мес)» — появился недавно, ещё может разогнаться;
  - «хронически слабый»   — давно в ассортименте, но продажи копеечные.

Период: последние 12 полных месяцев (2025-08-01 … 2026-07-31).
Единица — «история» товара (шринкфляция = продолжение, как в 07/10).

Выход: output/Группа_C_анализ.xlsx + печать в консоль.
"""

import pandas as pd

# ---------------------------------------------------------------
# Чтение и склейка в истории (как в 10)
# ---------------------------------------------------------------
df = pd.read_excel(
    "data/Молоко.xlsx",
    dtype={"Код номенклатуры": str},
    parse_dates=["День"],
)
pairs = pd.read_excel("output/пары_шринкфляции.xlsx", dtype=str)

chain_map = {}
for _, p in pairs.iterrows():
    chain_map[p["Код старой упаковки"]] = p["Код старой упаковки"]
    chain_map[p["Код новой упаковки"]] = p["Код старой упаковки"]
for code in df["Код номенклатуры"].unique():
    chain_map.setdefault(code, code)

df["История"] = df["Код номенклатуры"].map(chain_map)

chain_names = {}
for _, p in pairs.iterrows():
    chain_names[p["Код старой упаковки"]] = (
        f"{p['Название старой упаковки'][:38]} → {p['Название новой упаковки'][:38]}"
    )
first_name = df.groupby("Код номенклатуры")["Номенклатура"].first().to_dict()


def history_label(h: str) -> str:
    return chain_names.get(h, first_name[h])


recent = df[(df["День"] >= "2025-08-01") & (df["День"] <= "2026-07-31")]

# ---------------------------------------------------------------
# ABC по выручке → отбираем группу C
# ---------------------------------------------------------------
g = recent.groupby("История")["ТО, руб"].sum().sort_values(ascending=False)
g = g[g > 0]
cum = g.cumsum() / g.sum()
group = pd.Series("C", index=g.index)
group[cum <= 0.80] = "A"
group[(cum > 0.80) & (cum <= 0.95)] = "B"

c_hist = g[group == "C"].index
print("=" * 78)
print(f"ГРУППА C: {len(c_hist)} историй из {len(g)} — "
      f"{g[c_hist].sum() / g.sum():.1%} выручки за 12 мес".replace(",", " "))
print("=" * 78)

# ---------------------------------------------------------------
# Детали по каждому товару группы C
# ---------------------------------------------------------------
per_hist = recent.groupby("История").agg(
    Выручка=("ТО, руб", "sum"),
    Штук=("ТО, в е.изм.", "sum"),
)
first_sale = df.groupby("История")["День"].min()
last_sale = df.groupby("История")["День"].max()

END = pd.Timestamp("2026-07-31")

rows = []
for h in c_hist:
    first = first_sale[h]
    last = last_sale[h]
    rub = per_hist.loc[h, "Выручка"]
    qty = per_hist.loc[h, "Штук"]
    # динамика: последние 3 мес (май–июл 2026) vs предыдущие 3 (фев–апр 2026)
    q_now = recent[(recent["История"] == h) & (recent["День"] >= "2026-05-01")]["ТО, в е.изм."].sum()
    q_prev = recent[(recent["История"] == h) & (recent["День"] < "2026-05-01")]["ТО, в е.изм."].sum()
    dyn = (q_now / q_prev - 1) if q_prev > 0 else None
    # статус
    if (END - last).days > 90:
        status = "не продаётся 3+ мес"
    elif first >= pd.Timestamp("2025-08-01"):
        status = "новинка (до 12 мес)"
    else:
        status = "хронически слабый"
    rows.append(
        {
            "Название товара (история)": history_label(h),
            "Код истории": h,
            "Выручка за 12 мес, руб": round(rub, 2),
            "Доля выручки, %": round(rub / g.sum() * 100, 2),
            "Продано за 12 мес, штук": int(qty),
            "Средняя цена, руб/шт": round(rub / qty, 2) if qty else None,
            "Первая продажа": first.date(),
            "Последняя продажа": last.date(),
            "Статус": status,
            "Динамика (посл. 3 мес vs пред. 3), %": round(dyn * 100, 1) if dyn is not None else None,
        }
    )

tbl = pd.DataFrame(rows).sort_values("Выручка за 12 мес, руб", ascending=False)

# ---------------------------------------------------------------
# Итоги по статусам
# ---------------------------------------------------------------
summary = (
    tbl.groupby("Статус")
    .agg(
        Товаров=("Название товара (история)", "size"),
        Выручка_руб=("Выручка за 12 мес, руб", "sum"),
        Штук=("Продано за 12 мес, штук", "sum"),
    )
    .reset_index()
)
summary["Доля товаров группы C, %"] = summary["Товаров"] / len(tbl) * 100
summary["Доля выручки группы C, %"] = summary["Выручка_руб"] / tbl["Выручка за 12 мес, руб"].sum() * 100
summary = summary.rename(
    columns={
        "Товаров": "Товаров, шт",
        "Выручка_руб": "Выручка за 12 мес, руб",
        "Штук": "Продано за 12 мес, штук",
    }
)

print("\nИтоги по статусам:")
print(summary.to_string(index=False))

print("\nПолный список группы C (по убыванию выручки):")
for _, r in tbl.iterrows():
    dv = r["Динамика (посл. 3 мес vs пред. 3), %"]
    dyn_txt = f"  динамика {dv:+.0f}%" if pd.notna(dv) else ""
    print(f"  {r['Выручка за 12 мес, руб']:>9,.0f} руб  {r['Продано за 12 мес, штук']:>5,} шт  "
          f"[{r['Статус']}]{dyn_txt}  {r['Название товара (история)'][:55]}".replace(",", " "))

# ---------------------------------------------------------------
# Сохранение книги
# ---------------------------------------------------------------
OUT = "output/Группа_C_анализ.xlsx"
with pd.ExcelWriter(OUT, engine="openpyxl") as writer:
    tbl.to_excel(writer, sheet_name="Товары_группы_C", index=False)
    summary.to_excel(writer, sheet_name="Итоги_по_статусам", index=False)

print(f"\nСохранено: {OUT}")
print("  Лист «Товары_группы_C»:", len(tbl), "историй")
print("  Лист «Итоги_по_статусам»:", len(summary), "статусов")
